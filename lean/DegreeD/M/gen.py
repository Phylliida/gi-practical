#!/usr/bin/env python3
"""Generate the `GI.DegreeD.M` copies of the HJ development's Run-dependent files.

The `Run`/`Exec` inductive of `Workspace/Algorithm/Procedure.lean` cannot be reused for the
dispatcher (M'), because its dispatcher constructors carry the order tests `Small` / `SmallZ`.
So we copy the Run-dependent files into the namespace `GI.DegreeD.M`, with the two constructors
changed; everything Run-independent is imported from upstream (`open GI.Algorithm`).
Run from the directory of this script: python3 gen.py
"""
import re, pathlib, sys

UP = pathlib.Path('/home/bepis/math/GraphIsomorphismLog2/Workspace')
HERE = pathlib.Path(__file__).resolve().parent

MAP = {  # upstream module -> M module
    'Workspace.Algorithm.Correctness': 'DegreeD.M.Correctness',
    'Workspace.Algorithm.Tree': 'DegreeD.M.Tree',
    'Workspace.Algorithm.PhaseTree': 'DegreeD.M.PhaseTree',
    'Workspace.Paper.TotalCost': 'DegreeD.M.TotalCost',
    'Workspace.Paper.PhaseRun': 'DegreeD.M.PhaseRun',
}

def header_fix(s):
    def imp(m):
        mod = m.group(1)
        return 'import ' + MAP.get(mod, mod)
    s = re.sub(r'^import (\S+)', imp, s, flags=re.M)
    return s

def to_m(s, extra_opens='GI.Algorithm GI.Paper'):
    # keep the docstring, retarget the namespace
    s = s.replace('namespace GI.Algorithm\n', f'namespace GI.DegreeD.M\n\nopen {extra_opens}\n', 1)
    s = s.replace('namespace GI.Paper\n', f'namespace GI.DegreeD.M\n\nopen {extra_opens}\n', 1)
    s = s.replace('end GI.Algorithm', 'end GI.DegreeD.M').replace('end GI.Paper', 'end GI.DegreeD.M')
    return s

def gen_run():
    src = (UP/'Algorithm/Procedure.lean').read_text(encoding='utf8')
    i = src.index('-- The injectivity theorems')
    j = src.index('\nend\n\nend GI.Algorithm')
    body = src[i:j] + '\nend\n'
    body = body.replace('(hsm : ¬ Q.SmallZ P.smallExp)', '(hsm : Structural P Q ∧ ExposedSplit Q)')
    assert 'Structural P Q' in body
    out = """import DegreeD.M.Dispatch

/-! # `M.Run`: the recursion with the dispatcher `(M′)`

Generated by `gen.py` from `Workspace/Algorithm/Procedure.lean`. The only changes from
`GI.Algorithm.Run`: the dispatcher step is `M.DispatchStep` (enumeration under `¬ Structural`,
not `Small`) and the normalization constructor carries `Structural` in place of `¬ SmallZ`. -/

namespace GI.DegreeD.M

open Equiv Equiv.Perm GI.Algorithm
open scoped Pointwise

""" + body + """
end GI.DegreeD.M
"""
    (HERE/'Run.lean').write_text(out, encoding='utf8')

def copy_file(rel, name, patch=None, opens='GI.Algorithm GI.Paper'):
    s = (UP/rel).read_text(encoding='utf8')
    s = header_fix(s)
    s = to_m(s, opens)
    if patch: s = patch(s)
    if 'import DegreeD.M.Run' not in s:
        # replace Workspace.Algorithm.Procedure import to bring M.Run and Dispatch
        s = s.replace('import Workspace.Algorithm.Procedure', 'import DegreeD.M.Run', 1)
    (HERE/name).write_text(s, encoding='utf8')

def main():
    gen_run()
    copy_file('Algorithm/Correctness.lean', 'Correctness.lean')
    copy_file('Algorithm/Tree.lean', 'Tree.lean')
    copy_file('Algorithm/PhaseTree.lean', 'PhaseTree.lean', patch=patch_phasetree)
    gen_scriptfam()
    gen_realruns_prefix()
    print('ok')

def patch_phasetree(s):
    # ClassOK.mult: enumeration rows are bounded in the analysis, not by the Row.mult column.
    s = s.replace("mult : (c.branches.length : ℝ) ≤ c.row.mult cc N\n",
                  "mult : (c.branches.length : ℝ) ≤ c.row.mult cc N ∨ rowIsEnum c.row\n")
    s = s.replace("/-! ### Classes -/\n",
                  "/-- The enumeration rows are the rows whose count is bounded in the analysis. -/\n"
                  "def rowIsEnum : Row → Prop\n  | .enumeration _ => True\n  | _ => False\n\n/-! ### Classes -/\n")
    # DispatchKind.row: field notation would need the upstream namespace
    s = s.replace("def DispatchKind.row : DispatchKind → Row", "def kindRow : DispatchKind → Row")
    s = s.replace("I.kind.row", "(kindRow I.kind)")
    s = s.replace("DispatchKind.row", "kindRow")
    # CapUpdate.Q_drop is defined in this namespace, field notation does not reach it
    s = s.replace("hcap.Q_drop hc.β_pos hβ1 hβq", "CapUpdate.Q_drop hcap hc.β_pos hβ1 hβq")
    # the mult fields
    s = s.replace("mult := by simp only [List.length_singleton, Nat.cast_one, Row.mult]; exact cc.one_le_b₀",
                  "mult := Or.inl (by simp only [List.length_singleton, Nat.cast_one, Row.mult]; exact cc.one_le_b₀)")
    enum_old = """      obtain ⟨hd2, hds, hn, hρ', horb⟩ := hf
      refine
        { valid := ⟨hd2, hds⟩
          mult := ?_
          inv := fun b hb u hu => (hbr b hb u hu).choose_spec.choose_spec.2.2.1
          pos := fun b hb u hu => (hbr b hb u hu).choose_spec.choose_spec.2.2.2
          disj := hdisj
          child := fun b hb u hu => ?_ }
      · simp only [kindRow, Row.mult, List.length_ofFn]
        have hexp : Real.exp (P.a * Real.log d ^ 2) ≤ Real.exp (cc.a * Real.log d ^ 2) :=
          Real.exp_le_exp.2 (mul_le_mul_of_nonneg_right hc.a_le (sq_nonneg _))
        have := Real.exp_pos (cc.a * Real.log d ^ 2)
        nlinarith
"""
    enum_new = """      obtain ⟨hd2, hds, hρ', horb⟩ := hf
      refine
        { valid := ⟨hd2, hds⟩
          mult := Or.inr trivial
          inv := fun b hb u hu => (hbr b hb u hu).choose_spec.choose_spec.2.2.1
          pos := fun b hb u hu => (hbr b hb u hu).choose_spec.choose_spec.2.2.2
          disj := hdisj
          child := fun b hb u hu => ?_ }
"""
    assert enum_old in s
    s = s.replace(enum_old, enum_new)
    s = s.replace("mult := ?_", "mult := Or.inl ?_")
    # the HJ form of the hypotheses (with the Row.mult column) is not used
    i = s.index("theorem phaseTree_hyp")
    j = s.rindex("end GI.DegreeD.M")
    # drop a docstring preceding phaseTree_hyp, if any
    k = s.rfind("/--", 0, i)
    if s[k:i].count('-/') == 1 and s[k:i].rstrip().endswith('-/'):
        i = k
    s = s[:i] + "end Hyp\n\n" + s[j:]
    s = s.replace("hcap.rho_eq", "CapUpdate.rho_eq hcap")
    return s

def gen_scriptfam():
    src=(HERE.parent/'ScriptFamilies.lean').read_text(encoding='utf8')
    i=src.index('theorem Exec.contSizes_eq')
    j=src.rindex('end GI.Algorithm')
    body=src[i:j]
    out = """import DegreeD.ScriptFamilies
import DegreeD.M.PhaseTree

/-! # The call regrouping `(H2)` on the runs of `M.Run`

Generated by `gen.py` from `DegreeD/ScriptFamilies.lean`. Only `Exec.contSizes_eq` and
`aggregate_branch_fam` depend on the run type; the families of the scripts themselves are
reused from there. -/

namespace GI.DegreeD.M

open Equiv Equiv.Perm GI.Algorithm GI.Paper GI.DegreeD GI.Endpoint GI.LocalGroups GI.LocalCertificates
open scoped Pointwise
open Classical in
""" 
    out = out + "\nvariable {P : Params}\n\n" + body + "\nend GI.DegreeD.M\n"
    out = out.replace("open Classical in\n\nvariable", "variable")
    (HERE/'ScriptFam.lean').write_text(out, encoding='utf8')

def gen_realruns_prefix():
    src=(HERE.parent/'RealRuns.lean').read_text(encoding='utf8')
    i=src.index('/-! ### The phase tree restricted to a good set of vertices -/')
    pre=src[:i]
    pre=pre.replace('import DegreeD.ScriptFamilies\nimport DegreeD.RStarColumns\nimport DegreeD.HJInstance\n',
                    'import DegreeD.M.ScriptFam\nimport DegreeD.RStarColumns\n')
    pre=pre.replace('namespace GI.Algorithm\n','namespace GI.DegreeD.M\n')
    pre=pre.replace('open Equiv Equiv.Perm GI.Paper GI.DegreeD\n','open Equiv Equiv.Perm GI.Paper GI.DegreeD GI.Algorithm\n')
    pre=pre.replace('I.kind.row','(kindRow I.kind)')
    pre=pre.replace('exact (hok _ (by simp [giantClasses])).mult',
                    'exact (hok _ (by simp [giantClasses])).mult.resolve_right (by simp [rowIsEnum])')
    suf=(HERE/'RealRunsSuffix.template').read_text(encoding='utf8')
    (HERE/'RealRuns.lean').write_text(pre+suf, encoding='utf8')

if __name__ == '__main__':
    main()
