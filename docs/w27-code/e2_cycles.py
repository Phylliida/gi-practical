"""E2: for C-invariant graphs Gamma on [b]^M (one orbital of C, symmetrised), how much of the F_2 cycle
space is generated by short cycles (triangles/4-cycles, and <=6-cycles)? Guides the local-to-global question
for gauge objects (docs/w27-tree.md, section 2.5)."""
import itertools, random, sys
from collections import defaultdict

seed = int(sys.argv[1]) if len(sys.argv) > 1 else 1
rng = random.Random(seed)


def gens_S(b): return [tuple((i + 1) % b for i in range(b)), tuple([1, 0] + list(range(2, b)))]
def gens_A(b): return [tuple((i + 1) % b for i in range(b)), tuple([1, 2, 0] + list(range(3, b)))]
def gens_Z(b): return [tuple((i + 1) % b for i in range(b))]
def gens_AGL15(): return [tuple((i + 1) % 5 for i in range(5)), tuple(2 * i % 5 for i in range(5))]
def gens_PSL25():  # on projective line {0..4, inf=5}
    def op(f): return tuple(f(i) for i in range(6))
    def add(x): return 5 if x == 5 else (x + 1) % 5
    def mult(x): return 5 if x == 5 else (4 * x) % 5
    def inv(x):
        if x == 5: return 0
        if x == 0: return 5
        return (-pow(x, -1, 5)) % 5
    return [op(add), op(mult), op(inv)]


def product_gens(local, M):
    gs = []
    for j in range(M):
        for g in local:
            gs.append(('coord', j, g))
    return gs


def act(gen, v):
    kind, j, g = gen
    w = list(v); w[j] = g[w[j]]; return tuple(w)


def orbital(b, M, gens, v0, w0):
    seen = {(v0, w0)}; q = [(v0, w0)]
    while q:
        (u, w) = q.pop()
        for g in gens:
            p = (act(g, u), act(g, w))
            if p not in seen:
                seen.add(p); q.append(p)
    return seen


def analyse(b, M, gens, v0, w0, name):
    pairs = orbital(b, M, gens, v0, w0)
    E = set(frozenset(p) for p in pairs if p[0] != p[1])
    edges = sorted(tuple(sorted(e)) for e in E)
    eid = {e: i for i, e in enumerate(edges)}
    adj = defaultdict(set)
    for u, v in edges:
        adj[u].add(v); adj[v].add(u)
    verts = list(adj)
    if not verts:
        return None
    # components
    seen = set(); comps = 0
    for s in verts:
        if s in seen: continue
        comps += 1
        st = [s]; seen.add(s)
        while st:
            u = st.pop()
            for v in adj[u]:
                if v not in seen:
                    seen.add(v); st.append(v)
    rank_full = len(edges) - len(verts) + comps
    if rank_full == 0:
        return (name, len(verts), len(edges), 0, 0, 0)
    def eidp(a, b_):
        return eid[tuple(sorted((a, b_)))]

    basis = {}
    def add(vec):
        while vec:
            h = vec.bit_length() - 1
            if h in basis:
                vec ^= basis[h]
            else:
                basis[h] = vec
                return True
        return False

    rk = 0
    # triangles & 4-cycles
    cap = 400000
    cnt = 0
    for u in verts:
        nb = sorted(adj[u])
        for i, v in enumerate(nb):
            for w in nb[i + 1:]:
                cnt += 1
                if cnt > cap: break
                if v in adj[w]:
                    if add((1 << eidp(u, v)) ^ (1 << eidp(u, w)) ^ (1 << eidp(v, w))):
                        rk += 1
                for x in adj[v] & adj[w]:
                    if x != u:
                        if add((1 << eidp(u, v)) ^ (1 << eidp(u, w)) ^ (1 << eidp(x, v)) ^ (1 << eidp(x, w))):
                            rk += 1
            if rk == rank_full or cnt > cap: break
        if rk == rank_full or cnt > cap: break
    rk4 = rk
    # 5,6-cycles by BFS-sampling: sampled closed walks of length <=6 through random u
    if rk < rank_full:
        for _ in range(60000):
            u = rng.choice(verts)
            path = [u]
            for step in range(rng.choice([4, 5])):
                nxt = [v for v in adj[path[-1]] if v not in path]
                if not nxt: break
                path.append(rng.choice(nxt))
            if len(path) >= 3 and path[0] in adj[path[-1]]:
                vec = 0
                L = path + [path[0]]
                for a, c in zip(L, L[1:]):
                    vec ^= 1 << eidp(a, c)
                if add(vec):
                    rk += 1
            if rk == rank_full: break
    rk6 = rk
    return (name, len(verts), len(edges), rank_full, rk4, rk6)


groups = [
    ("S5", 5, 3, gens_S(5)),
    ("A5", 5, 3, gens_A(5)),
    ("PSL(2,5)/6pt", 6, 2, gens_PSL25()),
    ("AGL(1,5)", 5, 3, gens_AGL15()),
    ("S5", 5, 2, gens_S(5)),
    ("Z5", 5, 3, gens_Z(5)),
    ("Z3", 3, 5, gens_Z(3)),
    ("A4", 4, 3, gens_A(4)),
]

print("group b M | orbital | V E cyc_rank rank<=4 rank<=6 | gen by <=4 ? <=6 ?")
for name, b, M, loc in groups:
    gens = product_gens(loc, M)
    pts = list(itertools.product(range(b), repeat=M))
    seen_keys = set()
    tries = 0
    done = 0
    while done < 4 and tries < 80:
        tries += 1
        v0 = pts[rng.randrange(len(pts))]
        # choose w0 differing in random subset of coordinates
        k = rng.randint(1, M)
        I = rng.sample(range(M), k)
        w = list(v0)
        for j in I:
            w[j] = rng.choice([x for x in range(b) if x != w[j]])
        w0 = tuple(w)
        key = (frozenset(I))
        if key in seen_keys and name != 'Z5':
            continue
        seen_keys.add(key)
        res = analyse(b, M, gens, v0, w0, name)
        done += 1
        if res is None:
            continue
        nm, V, E, R, r4, r6 = res
        print(f"{nm:14s} {b} {M} | I={sorted(I)} | {V} {E} {R} {r4} {r6} | {'YES' if r4 == R else 'no'} {'YES' if r6 == R else 'no'}")
