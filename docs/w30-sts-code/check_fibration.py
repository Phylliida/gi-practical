"""Verify directly (exhaustively for the given S) the conclusion of Theorem 1 on instances with nontrivial
projective quotient: all extensions of S exact doublings, cosets equal, third-coset property, quotient PG(d-1,2).
S is taken as the closure of a triple generating 15 points in the central extension X_g (k=1)."""
import itertools, math, random
import sts


def verify(Q, seeds):
    n = len(Q)
    Sset = {i for i, v in enumerate(sts.closure(Q, seeds)) if v}
    s = len(Sset)
    out = [x for x in range(n) if x not in Sset]
    coset = {}
    cos = []
    for x in out:
        if x in coset:
            continue
        T = sts.closure(Q, sorted(Sset) + [x])
        mem = [v for v in out if T[v]]
        for v in mem:
            if v in coset:
                return f"partition failed at {v}"
            coset[v] = len(cos)
        cos.append(mem)
    sizes = {len(c) for c in cos}
    if len(sizes) != 1:
        return f"S size {s}, unequal coset sizes {sorted(sizes)}"
    a = sizes.pop()
    p = len(cos)
    third = {}
    for i, j in itertools.combinations(range(p), 2):
        ts = {coset.get(Q[x][y], -1) for x in cos[i] for y in cos[j]}
        if len(ts) != 1 or -1 in ts:
            return f"S size {s}: third coset fails for {i},{j}: {ts}"
        third[(i, j)] = ts.pop()
    P = [[-1] * p for _ in range(p)]
    for i in range(p):
        P[i][i] = i
    for (i, j), t in third.items():
        P[i][j] = P[j][i] = t
    if not sts.is_sts(P):
        return f"S size {s}: quotient not an STS"
    d = math.log2(p + 1)
    if d != int(d):
        return f"S size {s}: p+1 not power of 2 ({p})"
    bad = 0
    for i, j, k in itertools.combinations(range(p), 3):
        if P[i][j] != k and sts.closure_size(P, [i, j, k]) != 7:
            bad += 1
    if bad:
        return f"S size {s}: {bad} non-Fano quotient triangles"
    return f"OK: S size {s}, {p} cosets of size {a}, quotient PG({int(d)-1},2); a==s+1: {a == s + 1}"


rng = random.Random(5)
for d in (5, 6, 7):
    g = sts.random_g(d, 1, rng)
    Q = sts.x_fib(d, 1, lambda c: 0, {1: [(0, 1)]}, g)
    n = len(Q)
    # find a triple closing to 15 (a non-associative triangle)
    while True:
        T = rng.sample(range(n), 3)
        if sts.closure_size(Q, T) == 15:
            break
    print(f"X_g d={d} n={n}:", verify(Q, T), flush=True)
for d in (4, 5):
    while True:
        F1 = sts.patterned_factorization_k8(rng)
        nf, sp, _ = sts.f1_acceptable(F1, 3)
        if nf and sp:
            break
    chi = {c: rng.randrange(2) for c in range(1, 1 << d)}
    Q = sts.x_fib(d, 3, lambda c: chi[c], F1)
    # S = Z\0 = points 0..6 (generated by 3 of them)
    print(f"X_chi d={d} n={len(Q)}, S = Z\\0:", verify(Q, [0, 1, 3]), flush=True)
