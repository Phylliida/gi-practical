# -- string canonizers ------------------------------------------------------------------
def _getter(t):
    """itemgetter(*t) returning a tuple also for len(t) == 1."""
    if len(t) == 1:
        a = t[0]
        return lambda x: (x[a],)
    return itemgetter(*t)


def _invariant(acts, x):
    """Whether x^g == x for every permutation g in acts."""
    for g in acts:
        if _getter(g)(x) != x:
            return False
    return True


def perm_canon(P, x, stats=None):
    """The least act(x, h) over h in the permutation group P (on positions
    0..m-1, read in this order), by depth-first search.

    Search over g = h^-1: the image string is s_g[p] = x[g[p]]. With the
    stabilizer chain of base 0, 1, ..., m-1, the node (l, t) is the set
    {s t : s in P^(l)} (P^(l) fixes 0..l-1), on which s_g[p] = s_t[p] for
    p < l; its children are (l+1, u t) for u = T[l][beta], beta in the orbit
    of l under P^(l), with s_(u t)[l] = s_t[beta]. Pruning (each keeps every
    least leaf up to the automorphisms found, so the search returns the least
    image and generators of all of Aut_P(x)):
      * value: children with a larger value at l than a sibling, and nodes
        whose prefix exceeds the best leaf's, contain no least leaf;
      * invariance: if s_t is invariant under P^(l), every leaf below has the
        string s_t; the node is a leaf, and t^-1 s t (s in P^(l)) are
        automorphisms of x;
      * automorphisms: a child whose image t[beta] lies in the orbit of an
        explored sibling's image under the known automorphisms fixing
        t[0..l-1] has the same subtree up to that automorphism.
    Two leaves g1, g2 with equal strings give the automorphism g1^-1 g2
    (x[a[q]] = x[q]). Every least leaf is equivalent under the automorphisms
    found to a visited least leaf (induction over the pruned tree), so they
    generate Aut_P(x).

    Returns (F, lam, gens): act(x, lam) == F (the least image), and gens
    generate Aut_P(F) = lam^-1 Aut_P(x) lam."""
    m = P.n
    x = tuple(x)
    gens = P.gens
    if not gens or _invariant(gens, x):
        return x, identity(m), list(gens)
    C = PermGroup(m, gens, base=range(m), order=P.order())
    T, S = C.T, C.S
    nt = [l for l in range(m) if len(T[l]) > 1]
    nlev = len(nt)
    idn = identity(m)
    best = [None, None]                 # least string so far, and its g
    auts, autset = [], set()
    nodes = [0]

    def add_aut(a):
        if a != idn and a not in autset:
            autset.add(a)
            auts.append(a)

    def leaf(t, y):
        if best[0] is None or y < best[0]:
            best[0], best[1] = y, t
        elif y == best[0]:
            add_aut(mul(inv(best[1]), t))

    def dfs(j, t):
        nodes[0] += 1
        y = _getter(t)(x)               # s_t
        l = nt[j] if j < nlev else m
        b = best[0]
        if b is not None and y[:l] > b[:l]:
            return
        if j == nlev:
            leaf(t, y)
            return
        Sl = S[l]
        for s in Sl:
            if _getter(s)(y) != y:
                break
        else:                           # s_t invariant under P^(l)
            ti = inv(t)
            for s in Sl:
                add_aut(mul(mul(ti, s), t))
            leaf(t, y)
            return
        Tl = T[l]
        mn = min(y[beta] for beta in Tl)
        kids = [beta for beta in Tl if y[beta] == mn]
        explored = []
        fixed = [t[q] for q in nt[:j]]
        for beta in kids:
            img = t[beta]
            if explored and auts:
                fix = [a for a in auts if all(a[p] == p for p in fixed)]
                if fix and _in_orbit(img, explored, fix):
                    continue
            dfs(j + 1, mul(Tl[beta], t))
            explored.append(img)

    dfs(0, idn)
    if stats is not None:
        stats["canon_perm_calls"] += 1
        stats["canon_perm_nodes"] += nodes[0]
        stats["canon_perm_max_degree"] = max(stats["canon_perm_max_degree"], m)
    F, bt = best
    lam = inv(bt)
    return F, lam, [mul(mul(bt, a), lam) for a in auts]


def _in_orbit(p, starts, gens):
    seen = set(starts)
    if p in seen:
        return True
    stack = list(starts)
    while stack:
        q = stack.pop()
        for a in gens:
            r = a[q]
            if r not in seen:
                if r == p:
                    return True
                seen.add(r)
                stack.append(r)
    return False


def _as_ea(G, n):
    """G as an EA2 if it is elementary abelian (a property of the group: its
    generators commute and are involutions), else None. PermGroup.gens is
    irredundant, hence a basis then."""
    if isinstance(G, EA2):
        return G
    if is_ea2(G.gens, n):
        return EA2(n, G.gens)
    return None


def canon_group(G, n, pos, pidx, x, image, stats):
    """Canonize the string x on the positions pos (ordered; pidx: position ->
    index) under the action of G (an EA2 or PermGroup on range(n)), where
    image(g, p) is the image of position p under g. Returns (a, U): a in G
    (None for the identity) with act(x, a) the canonical form, and U =
    Aut_G(act(x, a)) (an EA2 when elementary abelian, else a PermGroup)."""
    gens = G.gens
    if not gens:
        stats["canon_trivial"] += 1
        return None, G
    acts = [tuple([pidx[image(g, p)] for p in pos]) for g in gens]
    x = tuple(x)
    if _invariant(acts, x):
        stats["canon_invariant"] += 1
        return None, G
    E = _as_ea(G, n)
    if E is not None:
        stats["canon_ea"] += 1
        c, N = EAAction(len(E.gens), acts, len(pos)).canon(x)
        return (E.elem(c) if c else None), EA2(n, [E.elem(v) for v in N])
    stats["canon_perm"] += 1
    phi = ActionHom(G, len(pos), lambda g: tuple([pidx[image(g, p)] for p in pos]))
    P = phi.image_group()
    _, lamP, autsP = perm_canon(P, x, stats)
    a = phi.lift(lamP)
    K = phi.kernel()
    order = (PermGroup(len(pos), autsP).order() if autsP else 1) * K.order()
    U = PermGroup(n, [phi.lift(h) for h in autsP] + list(K.gens), order=order)
    return (None if a == identity(n) else a), (_as_ea(U, n) or U)


def _set_image(g, S):
    return frozenset([g[i] for i in S])


def _pair_image(g, e):
    p, q = g[e[0]], g[e[1]]
    return (p, q) if p < q else (q, p)


# -- rooted canonical forms ----------------------------------------------------------------
def canon_rooted_colors(g, u0, u1):
    """1-WL colors of g with u0, u1 individualized, named canonically: in each
    round a color is the rank of its signature (old color, sorted neighbour
    colors) among the round's signatures, so the names depend only on the
    rooted isomorphism type of (g, u0, u1) (g.col must be canonical too).
    Iterated until the number of classes stops growing."""
    nbr, n = g.nbr, g.n
    col = [c + 2 for c in g.col]
    col[u0], col[u1] = 0, 1
    k = len(set(col))
    while True:
        sig = [(col[v], tuple(sorted([col[w] for w in nbr[v]]))) for v in range(n)]
        rank = {s: i for i, s in enumerate(sorted(set(sig)))}
        col = [rank[s] for s in sig]
        if len(rank) == k:
            return col
        k = len(rank)


class RootedCanon:
    """The canonical labelling of the rooted graph (g, u0, u1) (g.col: the
    canonical 1-WL colors steering the layers; incol: the canonical names of
    the input colors, which the form contains). run() returns (lab, A, keys,
    better): lab[i] is the label of the vertex R.order[i], A = Aut(CF; 0, 1)
    on the labels (an EA2 or a PermGroup), and keys the layered key of CF:
    keys[0] = the root colors, keys[r + 1] = (input colors of the labels of
    layer r + 1, sorted codes of the edges from them to smaller layers and
    inside). Layer r + 1 of CF only adds edges at its own labels (later steps
    move earlier labels only by automorphisms of CF_r), so keys is fixed
    layer by layer; it is a function of CF and the (canonical) layer sizes,
    and determines CF. Rooted forms are compared by keys: with best (the
    keys of another root), run stops and returns None as soon as its prefix
    exceeds best; better says whether keys < best."""

    def __init__(self, g, u0, u1, incol, stats, layers="class"):
        col = canon_rooted_colors(g, u0, u1)
        plan = class_plan(g, col, u0, u1) if layers == "class" else None
        self.R = _Rooted(g, u0, u1, col, plan)
        self.n = g.n
        self.incol = [incol[v] for v in self.R.order]
        self.stats = stats

    def run(self, best=None):
        R = self.R
        lab, A = [0, 1], EA2(2, [])
        keys = [(self.incol[0], self.incol[1])]
        state = 0 if best is not None else -1      # 0: equal to best so far; -1: smaller
        if state == 0:
            if keys[0] > best[0]:
                return None
            if keys[0] < best[0]:
                state = -1
        for r in range(len(R.start) - 2):
            lab, A = self.step(r, lab, A)
            keys.append(self.layer_key(r, lab))
            if state == 0:
                b = best[r + 1] if r + 1 < len(best) else ()
                if keys[-1] > b:
                    self.stats["canon_roots_aborted"] += 1
                    return None
                if keys[-1] < b:
                    state = -1
        return lab, A, keys, state == -1

    def layer_key(self, r, lab):
        R, n = self.R, self.n
        b, c = R.start[r + 1], R.start[r + 2]
        cl = [0] * (c - b)
        es = []
        for t in range(b, c):
            lt = lab[t]
            cl[lt - b] = self.incol[t]
            for w in R.adj[t]:
                if w < b or t < w < c:
                    lw = lab[w]
                    es.append(lt * n + lw if lt < lw else lw * n + lt)
        es.sort()
        return (tuple(cl), tuple(es))

    def step(self, r, lab, A):
        R, st = self.R, self.stats
        st["canon_layers"] += 1
        b, c = R.start[r + 1], R.start[r + 2]
        col = R.col
        att = R.attachments(r)
        # phase 1: the label sets of the up-sets under A
        occ = {}
        for U, ts in att.items():
            occ[frozenset([lab[i] for i in U])] = ts
        gens = A.gens
        S_list = list(occ)
        seen = set(S_list)
        for S in S_list:                # (the list grows: closure under A)
            for g in gens:
                S2 = frozenset([g[i] for i in S])
                if S2 not in seen:
                    seen.add(S2)
                    S_list.append(S2)
        pos = sorted(S_list, key=lambda S: tuple(sorted(S)))
        pidx = {S: i for i, S in enumerate(pos)}
        vt = {S: tuple([col[t] for t in ts]) for S, ts in occ.items()}
        code = {v: i + 1 for i, v in enumerate(sorted(set(vt.values())))}
        x = [0] * len(pos)
        for S, v in vt.items():
            x[pidx[S]] = code[v]
        st["canon_phase1_max_degree"] = max(st["canon_phase1_max_degree"], len(pos))
        a1, U1 = canon_group(A, b, pos, pidx, x, _set_image, st)
        if not isinstance(U1, EA2):
            U1 = _as_ea(U1, b) or U1
        lab1 = list(lab) if a1 is None else [a1[i] for i in lab]
        # phase 2: new labels by the block rule; H = rho(U1) x| prod Sym(blocks)
        cls = {frozenset([lab1[i] for i in U]): ts for U, ts in att.items()}
        newlab = [0] * (c - b)
        blocks, sym = {}, []
        nxt = b
        for p, S in enumerate(pos):
            ts = cls.get(S)
            if ts is None:
                continue
            labs = range(nxt, nxt + len(ts))
            for t, l in zip(ts, labs):
                newlab[t - b] = l
            blocks[p] = labs
            i = 0
            while i < len(ts):
                j = i + 1
                while j < len(ts) and col[ts[j]] == col[ts[i]]:
                    j += 1
                if j - i >= 2:
                    sym.append((p, list(labs[i:j])))
                i = j
            nxt += len(ts)
        if nxt != c:
            raise AssertionError("RootedCanon: twin classes do not cover the layer")
        labfull = lab1 + newlab
        hU = []
        for u in U1.gens:
            full = list(u) + [0] * (c - b)
            for p, labs in blocks.items():
                q = pidx[frozenset([u[i] for i in pos[p]])]
                for l, l2 in zip(labs, blocks[q]):
                    full[l] = l2
            hU.append(tuple(full))
        ea = isinstance(U1, EA2) and all(len(bl) == 2 for _, bl in sym) and all(
            pidx[frozenset([u[i] for i in pos[p]])] == p for p, _ in sym for u in U1.gens)
        if ea:
            sw = []
            for _, (l1, l2) in sym:
                s = list(range(c))
                s[l1], s[l2] = l2, l1
                sw.append(tuple(s))
            H = EA2(c, hU + sw)
        else:
            order = U1.order() * prod(factorial(len(bl)) for _, bl in sym)
            sg = [tuple(range(b)) + tuple(h[b:]) for _, bl in sym for h in sym_gens(c, bl)]
            H = PermGroup(c, hU + sg, order=order)
        st["canon_phase2_max_log2_order"] = max(st["canon_phase2_max_log2_order"],
                                                H.order().bit_length() - 1)
        # inner edges of layer r + 1
        E2 = set()
        for t in range(b, c):
            for w in R.adj[t]:
                if t < w < c:
                    l1, l2 = newlab[t - b], newlab[w - b]
                    E2.add((l1, l2) if l1 < l2 else (l2, l1))
        if not E2:
            return labfull, H
        pl = list(E2)
        seen = set(pl)
        for e in pl:
            for h in H.gens:
                e2 = _pair_image(h, e)
                if e2 not in seen:
                    seen.add(e2)
                    pl.append(e2)
        pl.sort()
        pidx2 = {e: i for i, e in enumerate(pl)}
        x2 = [1 if e in E2 else 0 for e in pl]
        st["canon_phase2_max_degree"] = max(st["canon_phase2_max_degree"], len(pl))
        h0, A2 = canon_group(H, c, pl, pidx2, x2, _pair_image, st)
        if h0 is not None:
            labfull = [h0[l] for l in labfull]
        return labfull, A2


# -- connected graphs and whole graphs -----------------------------------------------------
def _form(g, L):
    """The labelled graph g^L: (colors by label, sorted edge codes i * n + j,
    i < j)."""
    n = g.n
    cl = [0] * n
    for v in range(n):
        cl[L[v]] = g.col[v]
    es = []
    for u in range(n):
        Lu = L[u]
        for v in g.nbr[u]:
            if u < v:
                Lv = L[v]
                es.append(Lu * n + Lv if Lu < Lv else Lv * n + Lu)
    es.sort()
    return tuple(cl), tuple(es)


def _root_class(G, edges):
    """The candidate root edges (indices into edges): an isomorphism-invariant
    class. Stage 1: the class of (profile(u), profile(v)) minimizing (size,
    key), where profile(v) = (color, the sizes of the spheres around v, by
    color when there are at most 4 colors); stage 2: within it, the class of
    gi.bounded.edge_invariants minimizing (size, invariant). Both keys are
    isomorphism invariants of oriented edges (G.col canonical), so every
    isomorphism maps the class of X onto the class of Y."""
    n, nbr, col = G.n, G.nbr, G.col
    cur = [1 << v for v in range(n)]
    spheres = [cur]
    while True:
        nxt = []
        for v in range(n):
            b = cur[v]
            for w in nbr[v]:
                b |= cur[w]
            nxt.append(b)
        if nxt == cur:
            break
        spheres.append([b ^ a for a, b in zip(cur, nxt)])
        cur = nxt
    masks = {}
    for v in range(n):
        masks[col[v]] = masks.get(col[v], 0) | (1 << v)
    cm = [m for _, m in sorted(masks.items())]
    if 1 < len(cm) <= 4:
        prof = [(col[v], tuple(tuple((s[v] & m).bit_count() for m in cm) for s in spheres))
                for v in range(n)]
    else:
        prof = [(col[v], tuple(s[v].bit_count() for s in spheres)) for v in range(n)]
    k1 = [(prof[u], prof[v]) for u, v in edges]
    cnt = Counter(k1)
    key = min(cnt, key=lambda k: (cnt[k], k))
    C1 = [f for f, k in enumerate(k1) if k == key]
    if len(C1) <= 1:
        return C1
    inv2 = edge_invariants(G, [edges[f] for f in C1])
    cnt = Counter(inv2)
    key = min(cnt, key=lambda k: (cnt[k], k))
    return [f for f, k in zip(C1, inv2) if k == key]


def canon_connected(g, stats, layers="class"):
    """(form, L, auts) for a connected _Graph g with canonical int colors:
    L[v] the label of v, form = _form(g, L) (a function of the isomorphism
    type), auts generators of Aut(g) (vertex permutations)."""
    n = g.n
    if n == 1:
        return ((g.col[0],), ()), [0], []
    gc = refine_1wl(g.nbr, g.nbr, list(g.col), list(g.col))[0]
    G = _Graph(g.nbr, gc)
    edges = [(u, v) for u in range(n) for v in g.nbr[u]]
    eidx = {e: i for i, e in enumerate(edges)}
    cand = _root_class(G, edges)
    parent = list(range(len(edges)))

    def find(v):
        while parent[v] != v:
            parent[v] = parent[parent[v]]
            v = parent[v]
        return v

    def absorb(a):
        for i, (u, v) in enumerate(edges):
            p, q = find(i), find(eidx[(a[u], a[v])])
            if p != q:
                parent[max(p, q)] = min(p, q)

    best = None                         # (keys, L, Linv)
    auts, done = [], []
    for f in cand:
        rf = find(f)
        if any(find(e) == rf for e in done):
            continue
        done.append(f)
        stats["canon_roots"] += 1
        u0, u1 = edges[f]
        rc = RootedCanon(G, u0, u1, g.col, stats, layers)
        res = rc.run(best[0] if best is not None else None)
        if res is None:                 # its key exceeds the best one: not a least root
            continue
        lab, A, keys, better = res
        L = [0] * n
        for i, v in enumerate(rc.R.order):
            L[v] = lab[i]
        Linv = [0] * n
        for v, l in enumerate(L):
            Linv[l] = v
        new = [tuple([Linv[a[L[v]]] for v in range(n)]) for a in A.gens]
        if better:
            best = (keys, L, Linv)
        else:                           # equal keys, so equal forms: an automorphism
            Bi = best[2]
            new.append(tuple([Bi[L[v]] for v in range(n)]))
        for a in new:
            absorb(a)
            auts.append(a)
    idn = identity(n)
    return _form(g, best[1]), best[1], [a for a in dict.fromkeys(auts) if a != idn]


def _color_names(colors, n):
    if colors is None:
        return [0] * n
    vals = set(colors)
    try:
        srt = sorted(vals)
    except TypeError:
        srt = sorted(vals, key=repr)
    rank = {v: i for i, v in enumerate(srt)}
    return [rank[c] for c in colors]


def canonical_labeling_lists(nbr, colors=None, stats=None, layers="class"):
    """(lab, aut_gens) for the graph with neighbour lists nbr (symmetric, no
    loops or repeats) and optional vertex colors: lab[v] is the canonical label
    of v, so relabel_lists(nbr, lab) (with colors moved along) is the
    canonical form, equal for two graphs iff they are isomorphic (colors
    respected); aut_gens generate Aut (vertex permutations, g[v] the image of
    v). stats: an optional Counter for the counters canon_*. layers: "class"
    (gi.bounded.class_plan, BFS when it gives up) or "bfs"."""
    n = len(nbr)
    stats = Counter() if stats is None else stats
    if n == 0:
        return (), []
    nbr = _check_lists(nbr)
    names = _color_names(colors, n)
    gx = _Graph(nbr, names)
    comps = []
    for part in _components(nbr):
        form, L, auts = canon_connected(_induced(gx, part), stats, layers)
        comps.append((len(part), form, part, L, auts))
    comps.sort(key=lambda t: (t[0], t[1]))
    lab = [0] * n
    gens = []
    off = 0
    prev = None
    for size, form, part, L, auts in comps:
        for i, v in enumerate(part):
            lab[v] = off + L[i]
        for a in auts:
            h = list(range(n))
            for i, v in enumerate(part):
                h[v] = part[a[i]]
            gens.append(tuple(h))
        if prev is not None and prev[0] == size and prev[1] == form:
            pp, pL = prev[2], prev[3]
            Li = [0] * size
            for i, l in enumerate(L):
                Li[l] = i
            pLi = [0] * size
            for i, l in enumerate(pL):
                pLi[l] = i
            h = list(range(n))
            for i, v in enumerate(pp):
                h[v] = part[Li[pL[i]]]
            for i, v in enumerate(part):
                h[v] = pp[pLi[L[i]]]
            gens.append(tuple(h))
        prev = (size, form, part, L)
        off += size
    return tuple(lab), gens


def canonical_labeling(X, colors=None, stats=None, layers="class"):
    """canonical_labeling_lists for an adjacency matrix X (0/1 rows of an
    undirected loopless graph)."""
    return canonical_labeling_lists(_neighbours(X), colors, stats, layers)


def relabel_lists(nbr, lab):
    """The graph with neighbour lists nbr relabelled by lab (vertex v becomes
    lab[v]), as neighbour lists."""
    n = len(nbr)
    out = [None] * n
    for v in range(n):
        out[lab[v]] = sorted(lab[w] for w in nbr[v])
    return out


def _form_of(nbr, lab, colors):
    n = len(nbr)
    es = []
    for u in range(n):
        for v in nbr[u]:
            if u < v:
                a, b = lab[u], lab[v]
                es.append(a * n + b if a < b else b * n + a)
    es.sort()
    if colors is None:
        cl = None
    else:
        cl = [None] * n
        for v in range(n):
            cl[lab[v]] = colors[v]
        cl = tuple(cl)
    return (n, cl, tuple(es))


def canonical_form_lists(nbr, colors=None, stats=None, layers="class"):
    """The canonical form of the graph (neighbour lists, optional colors): the
    hashable tuple (n, colors by label or None, sorted edge codes i * n + j for
    the edges {i, j}, i < j, of the relabelled graph). Two graphs have equal
    forms iff they are isomorphic (with colors)."""
    lab, _ = canonical_labeling_lists(nbr, colors, stats, layers)
    return _form_of(nbr, lab, colors)


def canonical_form(X, colors=None, stats=None, layers="class"):
    """canonical_form_lists for an adjacency matrix."""
    return canonical_form_lists(_neighbours(X), colors, stats, layers)


def canon_iso_lists(nx, ny, colors_x=None, colors_y=None, stats=None):
    """Isomorphism test by canonical forms (same return value as
    gi.bounded.bounded_iso_lists): None, or (sigma, aut_gens of X) with
    sigma = lab_X then lab_Y^-1."""
    if len(nx) != len(ny):
        return None
    lx, gens = canonical_labeling_lists(nx, colors_x, stats)
    ly, _ = canonical_labeling_lists(ny, colors_y, stats)
    if _form_of(nx, lx, colors_x) != _form_of(ny, ly, colors_y):
        return None
    yi = [0] * len(ly)
    for v, l in enumerate(ly):
        yi[l] = v
    return tuple(yi[l] for l in lx), gens


def canon_iso(X, Y, colors_x=None, colors_y=None, stats=None):
    """canon_iso_lists for adjacency matrices."""
    return canon_iso_lists(_neighbours(X), _neighbours(Y), colors_x, colors_y, stats)
