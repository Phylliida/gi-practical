"""Canonical labeling of graphs of bounded degree: the canonical version of
Luks's reduction (Babai-Luks 1983, Sec. 4.2-4.3; docs/canonization-bounded-
degree.md Sec. 8), on the layers of gi/bounded.py.

    from gi.canon import canonical_form, canonical_labeling
    cf = canonical_form(X)                  # X: adjacency matrix; hashable
    lab, aut_gens = canonical_labeling(X)   # lab[v]: the label of vertex v
    # canonical_form(X) == canonical_form(Y)  iff  X and Y are isomorphic

canonical_form_lists, canonical_labeling_lists take neighbour lists. Vertex
colors are supported (any sortable values); the form contains them.

Notation. A labelling of a graph X on V is a bijection lambda: V -> [n]; X^lambda
is the graph on [n]. A canonizer of a string x on an ordered domain under a
group H gives F_H(x) = a string in the H-orbit of x that depends only on that
orbit, and Lambda_H(x) = {h in H : x^h = F_H(x)} = Aut_H(x) h0 = h0 Aut_H(F)
(Definition 2.1 / Lemma 2.2 of the write-up). Labels are 0-based; permutations
follow gi.perm (mul(p, q) is p then q, x^g = act(x, g)).

1. Components. Each component C is canonized (form, labelling, Aut(C)); the
   components are placed on consecutive intervals of [n] sorted by (size,
   form). Aut(X) is generated by the components' groups and one swap of each
   two consecutive components with equal forms.

2. Edge rooting (connected X, >= 2 vertices). CF(X) = the least CF(X, f)
   over the oriented edges f = (u0, u1) of a canonical class K, where
   CF(X, f) is a rooted canonical form (u0 -> 0, u1 -> 1) and rooted forms
   are compared by their layered keys (RootedCanon: per layer, the colors
   and the new edges; equal keys iff equal forms). K is the class of
   oriented edges minimizing (size, key), first by the pair of sphere-size
   profiles of the ends, then within that by the edge invariants of
   gi.bounded; both keys are isomorphism invariants (on canonical 1-WL
   colors), so every isomorphism maps K onto the corresponding class.
   Edges of K are tried one per orbit of the automorphisms found so far
   (equal orbits give equal forms), and a root is abandoned as soon as its
   key prefix exceeds the best one. Two roots with equal keys give the
   automorphism lab_f lab_best^-1. Aut(X) is generated by Aut(X, f_best),
   these automorphisms and all others found: every edge of the least orbit
   is reached from f_best (it was either tried, or skipped as the image of
   a tried edge with the same, least, key).

3. Rooted canonical form. Each rooted graph gets rooted 1-WL colors named
   canonically (a color is the rank of its signature among the signatures of
   that round, so the names are a function of the rooted isomorphism type),
   and is layered by gi.bounded.class_plan (canonical: ties are broken by
   color names) or BFS layers. Call a labelling of X_r admissible if it maps
   the roots to 0, 1, each layer V_i onto its interval I_i of labels, and
   preserves the rooted colors (every rooted isomorphism is admissible). The
   invariant after layer r: lab_r is an admissible labelling of X_r, CF_r =
   X_r^lab_r (with the intervals and colors) depends only on the rooted
   isomorphism type, and A_r is the group of the admissible automorphisms of
   CF_r (on labels), so the admissible labellings of X_r onto CF_r are
   exactly lab_r A_r. (With class layers X_r may have automorphisms that are
   not admissible; at r = R every rooted automorphism of X is.) Step
   r -> r + 1 (the twin-class form of Luks's step in gi/bounded.py, on the
   label side):

   Phase 1. Each vertex w of layer r + 1 has its up-set (its neighbours in
   earlier layers); vertices with equal up-sets form twin classes. The label
   sets lab_r(up-set) are strings on the domain P1 of all A_r-images of these
   sets (a union of A_r-orbits, so the same set for every labelling in
   lab_r A_r), ordered by their sorted label tuples: x(S) = the rank of the
   color multiset of the twin class of S (0 if no class has S). For
   lambda = lab_r a, x_lambda = x^a, so all labellings give one A_r-orbit, and
   the canonizer gives F1 and the coset of a with x^a = F1. lab' = lab_r a1;
   U1 = Aut_{A_r}(F1).

   Phase 2. The new labels N_r, N_r + 1, ... go to the twin classes in the
   order of their sets in P1, each class by color; within a color the order
   is free. H = rho(U1) x| prod Sym(color blocks) acts on [N_(r+1)]: u in U1
   with the rank-wise map from the block of S onto the block of u(S). The
   inner edges of layer r + 1 (as label pairs) are a string on the domain P2
   of their H-images (1 on edges); the canonizer gives F2 and h0; lab_(r+1) =
   lab' h0 (extended), and A_(r+1) = Aut_H(F2) (A_(r+1) = H without inner
   edges).

   Exactness. CF_(r+1) is a function of CF_r, F1 and F2 (edges from a new
   label go to the labels of its set; its color is its block's; inner edges
   are F2), and F1, F2 depend only on orbits that are isomorphism invariants,
   so CF_(r+1) depends only on the rooted isomorphism type. Conversely every
   admissible labelling mu onto CF_(r+1) restricts to lab_r A_r, has x_mu = F1
   (the attachments of CF_(r+1) are F1), places the new vertices by the
   block rule and has inner edges F2, so mu is in lab_(r+1) Aut_H(F2); and
   Aut_H(F2) = A_(r+1) by the same argument (Claims 4-5 of Sec. 8 of the
   write-up). The order of positions and the method used below depend
   only on the group as a set (P1 of the write-up): elementary abelian or
   not is a property of the group, and both methods compute least images
   over the whole group.

4. String canonizers (canon_group):
   * trivial group, or x invariant under every generator: F = x, Lambda = H;
   * H elementary abelian (an independent basis of commuting involutions):
     EAAction.canon (gi/ea2.py), the least image in orbit-major order, by
     Gaussian elimination over F_2: orbit by orbit, the minimizers form an
     affine subspace, cut down by linear equations; no Schreier-Sims. This
     is the canonical counterpart of the isomorphism test of gi/ea2.py.
   * phase 2 when H = U1 x prod Sym(blocks), U1 fixing every position that
     holds a block (no generator moves a block): ir_canon, an
     individualization-refinement canonical form of the inner-edge graph
     colored by the blocks (a colored-graph canonization problem);
   * otherwise: perm_canon, the least image along positions 0, 1, ...: a
     depth-first search over a stabilizer chain with base 0, 1, ..., pruned
     by value, by invariance of a node's string under its stabilizer, and by
     the automorphisms found (as in individualization-refinement search).
     Exponential in the worst case, exact always.

Elementary abelian layer groups are kept sparse (gi.ea2.SparseEA: dicts of
moved points, extended in place layer by layer, with a point -> generators
index), so a step only touches the generators that move its points. The
choice among the canonizers above depends only on the group as a set
(elementary abelian or not, H a direct product over the blocks or not).
"""
