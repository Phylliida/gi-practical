def canon_rooted_colors(g, u0, u1):
    """1-WL colors of g with u0, u1 individualized (gi.wl.refine, starting
    from the equitable canonical coloring g.col), named canonically: the names
    depend only on the rooted isomorphism type of (g, u0, u1)."""
    return wl_refine(g.nbr, g.col, (u0, u1), True)


class RootedCanon:
    """The canonical labelling of the rooted graph (g, u0, u1) (g.col: the
    canonical 1-WL colors steering the layers; incol: the canonical names of
    the input colors, which the form contains). run() returns (lab, A, keys,
    better): lab[i] is the label of the vertex R.order[i], A the admissible
    automorphisms of CF on the labels (= Aut(X, u0, u1) moved to the labels;
    an EA2 or a PermGroup), and keys the layered key of CF:
    keys[0] = the root colors, keys[r + 1] = (input colors of the labels of
    layer r + 1, sorted codes of the edges from them to smaller layers and
    inside). Layer r + 1 of CF only adds edges at its own labels (later steps
    move earlier labels only by automorphisms of CF_r), so keys is fixed
    layer by layer; it is a function of CF and the (canonical) layer sizes,
    and determines CF. Rooted forms are compared by keys: with best (the
    keys of another root), run stops and returns None as soon as its prefix
    exceeds best; better says whether keys < best."""

    def __init__(self, g, u0, u1, incol, stats, layers="class"):
        col = canon_rooted_colors(g, u0, u1)
        plan = class_plan(g, col, u0, u1) if layers == "class" else None
        self.R = _Rooted(g, u0, u1, col, plan)
        self.n = g.n
        self.incol = [incol[v] for v in self.R.order]
        self.stats = stats

    def run(self, best=None):
        R = self.R
        lab, linv, A = [0, 1], [0, 1], SparseEA()
        keys = [(self.incol[0], self.incol[1])]
        state = 0 if best is not None else -1      # 0: equal to best so far; -1: smaller
        if state == 0:
            if keys[0] > best[0]:
                return None
            if keys[0] < best[0]:
                state = -1
        for r in range(len(R.start) - 2):
            A = self.step(r, lab, linv, A)
            keys.append(self.layer_key(r, lab))
            if state == 0:
                b = best[r + 1] if r + 1 < len(best) else ()
                if keys[-1] > b:
                    self.stats["canon_roots_aborted"] += 1
                    return None
                if keys[-1] < b:
                    state = -1
        return lab, A, keys, state == -1

    def layer_key(self, r, lab):
        R, n = self.R, self.n
        b, c = R.start[r + 1], R.start[r + 2]
        cl = [0] * (c - b)
        es = []
        for t in range(b, c):
            lt = lab[t]
            cl[lt - b] = self.incol[t]
            for w in R.adj[t]:
                if w < b or t < w < c:
                    lw = lab[w]
                    es.append(lt * n + lw if lt < lw else lw * n + lt)
        es.sort()
        return (tuple(cl), tuple(es))

    def step(self, r, lab, linv, A):
        """One layer: lab (index -> label) and linv (label -> index) are extended
        in place and the group A_(r+1) is returned (SparseEA or PermGroup)."""
        R, st = self.R, self.stats
        st["canon_layers"] += 1
        b, c = R.start[r + 1], R.start[r + 2]
        col = R.col
        att = R.attachments(r)
        sparse = isinstance(A, SparseEA)
        # phase 1: the label sets of the up-sets under A
        occ = {}
        for U, ts in att.items():
            occ[frozenset([lab[i] for i in U])] = ts
        table = acts1 = None            # the action of A on the positions, computed once
        res = None
        if _ck is not None:             # (compiled closure: pos sorted, the table on indices)
            res = (_ck.closure_sparse(list(occ), A.gens, A.who, 0) if sparse
                   else _ck.closure_dense(list(occ), A.gens, 0))
        if res is not None:
            pos, tb = res
            if sparse:
                table = tb
            else:
                acts1 = tb
            pidx = {S: i for i, S in enumerate(pos)}
        else:
            if sparse:
                S_list, table = _closure_sparse(occ, A, _set_image_sparse)
            else:
                S_list, rows = _closure_dense(occ, A.gens, _set_image)
            pos = sorted(S_list, key=lambda S: tuple(sorted(S)))
            pidx = {S: i for i, S in enumerate(pos)}
            if sparse:
                table = _table_to_pos(table, S_list, pidx)
            else:
                acts1 = _rows_to_pos(rows, S_list, pidx)
        vt = {S: tuple([col[t] for t in ts]) for S, ts in occ.items()}
        code = {v: i + 1 for i, v in enumerate(sorted(set(vt.values())))}
        x = [0] * len(pos)
        for S, v in vt.items():
            x[pidx[S]] = code[v]
        st["canon_phase1_max_degree"] = max(st["canon_phase1_max_degree"], len(pos))
        if sparse:
            a1, restricted = canon_sparse(A, pos, table, x, st, "_p1")
            U1 = A
            if restricted:
                table = None            # (new generators: the table no longer applies)
        else:
            a1, U1 = canon_group(A, b, pos, pidx, x, _set_image, st, "_p1", acts1)
            same = U1 is A              # (x invariant: acts1 is still U1's action)
            U1 = _as_sparse_ea(U1, b) or U1
            if isinstance(U1, SparseEA):
                if same:                # (from_tuples: ids 0, 1, ... in the order of A.gens)
                    table = {i: {p: q for p, q in enumerate(act) if p != q}
                             for i, act in enumerate(acts1)}
                acts1 = None
            elif not same:
                acts1 = None
        if a1 is not None:
            self._apply(lab, linv, a1, b, sparse)
        sparse = isinstance(U1, SparseEA)
        # phase 2: new labels by the block rule; H = rho(U1) x| prod Sym(blocks)
        cls = {frozenset([lab[i] for i in U]): ts for U, ts in att.items()}
        newlab = [0] * (c - b)
        blocks, sym = {}, []
        nxt = b
        for p, S in enumerate(pos):
            ts = cls.get(S)
            if ts is None:
                continue
            labs = range(nxt, nxt + len(ts))
            for t, l in zip(ts, labs):
                newlab[t - b] = l
            blocks[p] = labs
            i = 0
            while i < len(ts):
                j = i + 1
                while j < len(ts) and col[ts[j]] == col[ts[i]]:
                    j += 1
                if j - i >= 2:
                    sym.append((p, list(labs[i:j])))
                i = j
            nxt += len(ts)
        if nxt != c:
            raise AssertionError("RootedCanon: twin classes do not cover the layer")
        lab.extend(newlab)
        linv.extend([0] * (c - b))
        for t, l in zip(range(b, c), newlab):
            linv[l] = t
        # inner edges of layer r + 1
        E2 = set()
        for t in range(b, c):
            for w in R.adj[t]:
                if t < w < c:
                    l1, l2 = newlab[t - b], newlab[w - b]
                    E2.add((l1, l2) if l1 < l2 else (l2, l1))
        # H = U1 x prod Sym(blocks) when U1 fixes every position holding a block
        # (ie H acts on the new labels as the product of the symmetric groups on
        # the blocks): the inner-edge string is a colored graph (see ir_canon)
        fixed = bool(sym) and bool(E2)
        if sparse:
            if table is None:           # (U1 was restricted: its action on the positions)
                table = {}
                gens = U1.gens
                for gid in U1.active_on(set().union(*pos) if pos else ()):
                    g = gens[gid]
                    mv = {}
                    for p, S in enumerate(pos):
                        q = pidx[frozenset([g.get(i, i) for i in S])]
                        if q != p:
                            mv[p] = q
                    table[gid] = mv
            moved = set()               # the positions some generator moves
            for mv in table.values():
                moved.update(mv)
            if fixed and any(p in moved for p in blocks):
                fixed = False
            # is H elementary abelian? (a property of the group: U1 elementary abelian,
            # every block <= 2, U1 fixes the positions holding a block of 2.)
            ea = all(len(bl) == 2 for _, bl in sym) and not any(p in moved for p, _ in sym)
            if ea:
                # extend U1 in place by the rank-wise maps of the blocks, add the swaps
                for gid, mv in table.items():
                    e = {}
                    for p, q in mv.items():
                        labs = blocks.get(p)
                        if labs is not None:
                            for l, l2 in zip(labs, blocks[q]):
                                e[l] = l2
                    if e:
                        U1.extend(gid, e)
                for _, (l1, l2) in sym:
                    U1.add({l1: l2, l2: l1})
                H = U1
            elif fixed:
                return self._ir_layer(U1.tuples(b), U1.order(), b, c, E2, sym, lab, linv, st)
            else:
                H = self._dense_H(U1, pos, pidx, blocks, sym, b, c)
        else:
            if acts1 is None:           # (U1 is not A: its action on the positions)
                acts1 = [tuple([pidx[frozenset([u[i] for i in S])] for S in pos])
                         for u in U1.gens]
            if fixed and any(act[p] != p for act in acts1 for p in blocks):
                fixed = False
            if fixed:
                return self._ir_layer(list(U1.gens), U1.order(), b, c, E2, sym, lab, linv, st)
            H = self._perm_H(U1, acts1, blocks, sym, b, c)
        st["canon_phase2_max_log2_order"] = max(st["canon_phase2_max_log2_order"],
                                                H.order().bit_length() - 1)
        if not E2:
            return H
        if isinstance(H, SparseEA):
            res = _ck.closure_sparse(list(E2), H.gens, H.who, 1) if _ck is not None else None
            if res is not None:
                pl, table2 = res
                pidx2 = {e: i for i, e in enumerate(pl)}
            else:
                pl0, table2 = _closure_sparse(E2, H, _pair_image_sparse)
                pl = sorted(pl0)
                pidx2 = {e: i for i, e in enumerate(pl)}
                table2 = _table_to_pos(table2, pl0, pidx2)
            x2 = [1 if e in E2 else 0 for e in pl]
            st["canon_phase2_max_degree"] = max(st["canon_phase2_max_degree"], len(pl))
            h0, _ = canon_sparse(H, pl, table2, x2, st, "_p2")
            A2 = H
            if h0 is not None:
                self._apply(lab, linv, h0, c, True)
        else:
            res = _ck.closure_dense(list(E2), H.gens, 1) if _ck is not None else None
            if res is not None:
                pl, acts2 = res
                pidx2 = {e: i for i, e in enumerate(pl)}
            else:
                pl0, rows2 = _closure_dense(E2, H.gens, _pair_image)
                pl = sorted(pl0)
                pidx2 = {e: i for i, e in enumerate(pl)}
                acts2 = _rows_to_pos(rows2, pl0, pidx2)
            x2 = [1 if e in E2 else 0 for e in pl]
            st["canon_phase2_max_degree"] = max(st["canon_phase2_max_degree"], len(pl))
            h0, A2 = canon_group(H, c, pl, pidx2, x2, _pair_image, st, "_p2", acts2)
            if h0 is not None:
                self._apply(lab, linv, h0, c, False)
            A2 = _as_sparse_ea(A2, c) or A2
        return A2

    @staticmethod
    def _apply(lab, linv, a, n, sparse):
        """Replace lab by lab a (labels moved by a): lab[t] = a(old lab[t]);
        linv follows. sparse: a is a dict of the moved labels (< n),
        else a tuple."""
        items = a.items() if sparse else ((l, a[l]) for l in range(n) if a[l] != l)
        ups = [(linv[l], l2) for l, l2 in items if l < n]
        for t, l2 in ups:
            lab[t] = l2
            linv[l2] = t

    def _ir_layer(self, Ugens, Uorder, b, c, E2, sym, lab, linv, st):
        """Phase 2 when H = U1 x prod Sym(blocks), U1 fixing every position
        holding a block: U1 moves no new label, the inner-edge string is the
        graph E2 on the new labels and H acts on it through prod Sym(blocks),
        so its canonical form is that of a colored graph (colors: the blocks,
        canonical since the blocks are sets of labels). Canonized by
        ir_canon; lab is updated, and A_(r+1) = U1 x Aut(colored graph) is
        returned."""
        st["canon_ir"] += 1
        nv = c - b
        col0 = list(range(nv))          # singletons keep their own color
        for _, bl in sym:
            m = bl[0] - b
            for l in bl:
                col0[l - b] = m
        adj = [[] for _ in range(nv)]
        for l1, l2 in E2:
            u, v = l1 - b, l2 - b
            adj[u].append(v)
            adj[v].append(u)
        rel, auts = ir_canon(adj, col0)
        h0 = {b + v: b + w for v, w in enumerate(rel) if v != w}
        if h0:
            self._apply(lab, linv, h0, c, True)
        relinv = [0] * nv
        for v, w in enumerate(rel):
            relinv[w] = v
        gens = [tuple(g) + tuple(range(b, c)) for g in Ugens]
        for a in auts:                  # Aut(F2) = rel^-1 Aut(graph) rel on new labels
            g = list(range(c))
            for v in range(nv):
                g[b + rel[v]] = b + rel[a[v]]
            gens.append(tuple(g))
        gens = [g for g in dict.fromkeys(gens) if g != tuple(range(c))]
        A2 = PermGroup(c, gens)
        return _as_sparse_ea(A2, c) or A2

    @staticmethod
    def _dense_H(U1, pos, pidx, blocks, sym, b, c):
        """H as a PermGroup, from a SparseEA U1 (a layer where H is not
        elementary abelian)."""
        hU = []
        for u in U1.tuples(b):
            full = list(u) + [0] * (c - b)
            for p, labs in blocks.items():
                q = pidx[frozenset([u[i] for i in pos[p]])]
                for l, l2 in zip(labs, blocks[q]):
                    full[l] = l2
            hU.append(tuple(full))
        order = U1.order() * prod(factorial(len(bl)) for _, bl in sym)
        sg = [tuple(range(b)) + tuple(h[b:]) for _, bl in sym for h in sym_gens(c, bl)]
        return PermGroup(c, hU + sg, order=order)

    @staticmethod
    def _perm_H(U1, acts, blocks, sym, b, c):
        """H = rho(U1) x| prod Sym(blocks) from a PermGroup U1, with acts[i][p] =
        the image of position p under U1.gens[i], as a _LazyGroup: its .gens are
        exactly those of PermGroup(c, hU + sg, order=|H|) (the generators
        of U1 extended rank-wise, the generators of the Sym of the first block
        of each U1-orbit of positions, for each color block: a Sym generator of
        another block of that orbit, same rank range, is conjugate under the
        extension of the U1-element mapping the position, so redundant; a
        generator of a block in a new orbit is never redundant, since
        rank-wise extensions act trivially inside a block), and its stabilizer
        chain is built only if something asks for it (see _LazyGroup)."""
        hU = []
        items = list(blocks.items())
        for u, act in zip(U1.gens, acts):
            full = list(u) + [0] * (c - b)
            for p, labs in items:
                for l, l2 in zip(labs, blocks[act[p]]):
                    full[l] = l2
            hU.append(tuple(full))
        order = U1.order() * prod(factorial(len(bl)) for _, bl in sym)
        sg = []
        if sym:
            orb = _orbit_index(acts, max(p for p, _ in sym) + 1, len(acts[0]) if acts else None)
            seen = set()
            base = tuple(range(b))
            for p, bl in sym:
                key = (orb[p] if orb is not None else p, bl[0] - blocks[p][0])
                if key not in seen:
                    seen.add(key)
                    for h in sym_gens(c, bl):
                        sg.append(base + tuple(h[b:]))
        return _LazyGroup(c, hU + sg, order)


# -- connected graphs and whole graphs -----------------------------------------------------
def _form(g, L):
    """The labelled graph g^L: (colors by label, sorted edge codes i * n + j,
    i < j)."""
    n = g.n
    cl = [0] * n
    for v in range(n):
        cl[L[v]] = g.col[v]
    es = []
    for u in range(n):
        Lu = L[u]
        for v in g.nbr[u]:
            if u < v:
                Lv = L[v]
                es.append(Lu * n + Lv if Lu < Lv else Lv * n + Lu)
    es.sort()
    return tuple(cl), tuple(es)


def _root_class(G, edges):
    """The candidate root edges (indices into edges): an isomorphism-invariant
    class (gi.bounded.root_class; G.col canonical)."""
    return root_class(G, edges)[0]


def canon_connected(g, stats, layers="class"):
    """(form, L, auts) for a connected _Graph g with canonical int colors:
    L[v] the label of v, form = _form(g, L) (a function of the isomorphism
    type), auts generators of Aut(g) (vertex permutations)."""
    n = g.n
    if n == 1:
        return ((g.col[0],), ()), [0], []
    gc = wl_refine(g.nbr, g.col)        # canonical: g.col is canonical
    G = _Graph(g.nbr, gc)
    edges = [(u, v) for u in range(n) for v in g.nbr[u]]
    eidx = {e: i for i, e in enumerate(edges)}
    cand = _root_class(G, edges)
    pos = {f: i for i, f in enumerate(cand)}
    parent = list(range(len(cand)))

    def find(v):
        while parent[v] != v:
            parent[v] = parent[parent[v]]
            v = parent[v]
        return v

    comps = [len(cand)]                 # number of orbits of the found automorphisms on K
    tbl = _ck.orbit_table(g.nbr, cand) if _ck is not None else None

    def absorb(a):
        if comps[0] == 1:               # K is one orbit: more generators change nothing
            return
        if tbl is not None:             # (compiled; parent stays valid for find)
            r = _ck.orbit_absorb(tbl, parent, comps[0], a)
            if r is not None:
                comps[0] -= r
                return
        for i, f in enumerate(cand):    # (automorphisms map the class K onto itself)
            u, v = edges[f]
            p, q = find(i), find(pos[eidx[(a[u], a[v])]])
            if p != q:
                parent[max(p, q)] = min(p, q)
                comps[0] -= 1

    best = None                         # (keys, L, Linv)
    auts, done = [], []
    for fi, f in enumerate(cand):
        if done and comps[0] == 1:      # K is one orbit: every edge is an image of a tried one
            break
        rf = find(fi)
        if any(find(e) == rf for e in done):
            continue
        done.append(fi)
        stats["canon_roots"] += 1
        u0, u1 = edges[f]
        rc = RootedCanon(G, u0, u1, g.col, stats, layers)
        res = rc.run(best[0] if best is not None else None)
        if res is None:                 # its key exceeds the best one: not a least root
            continue
        lab, A, keys, better = res
        L = [0] * n
        for i, v in enumerate(rc.R.order):
            L[v] = lab[i]
        Linv = [0] * n
        for v, l in enumerate(L):
            Linv[l] = v
        gs = A.tuples(n) if isinstance(A, SparseEA) else A.gens
        if _ck is not None:
            Lt, Lit = tuple(L), tuple(Linv)
            new = [mul(mul(Lt, a), Lit) for a in gs]
        else:
            new = [tuple([Linv[a[L[v]]] for v in range(n)]) for a in gs]
        if better:
            best = (keys, L, Linv)
        else:                           # equal keys, so equal forms: an automorphism
            Bi = best[2]
            new.append(tuple([Bi[L[v]] for v in range(n)]))
        for a in new:
            absorb(a)
            auts.append(a)
    idn = identity(n)
    return _form(g, best[1]), best[1], [a for a in dict.fromkeys(auts) if a != idn]


def _color_names(colors, n):
    if colors is None:
        return [0] * n
    vals = set(colors)
    try:
        srt = sorted(vals)
    except TypeError:
        srt = sorted(vals, key=repr)
    rank = {v: i for i, v in enumerate(srt)}
    return [rank[c] for c in colors]


def canonical_labeling_lists(nbr, colors=None, stats=None, layers="class"):
    """(lab, aut_gens) for the graph with neighbour lists nbr (symmetric, no
    loops or repeats) and optional vertex colors: lab[v] is the canonical label
    of v, so relabel_lists(nbr, lab) (with colors moved along) is the
    canonical form, equal for two graphs iff they are isomorphic (colors
    respected); aut_gens generate Aut (vertex permutations, g[v] the image of
    v). stats: an optional Counter for the counters canon_*. layers: "class"
    (gi.bounded.class_plan, BFS when it gives up) or "bfs"."""
    n = len(nbr)
    stats = Counter() if stats is None else stats
    if n == 0:
        return (), []
    nbr = _check_lists(nbr)
    names = _color_names(colors, n)
    gx = _Graph(nbr, names)
    comps = []
    for part in _components(nbr):
        form, L, auts = canon_connected(_induced(gx, part), stats, layers)
        comps.append((len(part), form, part, L, auts))
    comps.sort(key=lambda t: (t[0], t[1]))
    lab = [0] * n
    gens = []
    off = 0
    prev = None
    for size, form, part, L, auts in comps:
        for i, v in enumerate(part):
            lab[v] = off + L[i]
        for a in auts:
            h = list(range(n))
            for i, v in enumerate(part):
                h[v] = part[a[i]]
            gens.append(tuple(h))
        if prev is not None and prev[0] == size and prev[1] == form:
            pp, pL = prev[2], prev[3]
            Li = [0] * size
            for i, l in enumerate(L):
                Li[l] = i
            pLi = [0] * size
            for i, l in enumerate(pL):
                pLi[l] = i
            h = list(range(n))
            for i, v in enumerate(pp):
                h[v] = part[Li[pL[i]]]
            for i, v in enumerate(part):
                h[v] = pp[pLi[L[i]]]
            gens.append(tuple(h))
        prev = (size, form, part, L)
        off += size
    return tuple(lab), gens


def canonical_labeling(X, colors=None, stats=None, layers="class"):
    """canonical_labeling_lists for an adjacency matrix X (0/1 rows of an
    undirected loopless graph)."""
    return canonical_labeling_lists(_neighbours(X), colors, stats, layers)


def relabel_lists(nbr, lab):
    """The graph with neighbour lists nbr relabelled by lab (vertex v becomes
    lab[v]), as neighbour lists."""
    n = len(nbr)
    out = [None] * n
    for v in range(n):
        out[lab[v]] = sorted(lab[w] for w in nbr[v])
    return out


def _form_of(nbr, lab, colors):
    n = len(nbr)
    es = []
    for u in range(n):
        for v in nbr[u]:
            if u < v:
                a, b = lab[u], lab[v]
                es.append(a * n + b if a < b else b * n + a)
    es.sort()
    if colors is None:
        cl = None
    else:
        cl = [None] * n
        for v in range(n):
            cl[lab[v]] = colors[v]
        cl = tuple(cl)
    return (n, cl, tuple(es))


def canonical_form_lists(nbr, colors=None, stats=None, layers="class"):
    """The canonical form of the graph (neighbour lists, optional colors): the
    hashable tuple (n, colors by label or None, sorted edge codes i * n + j for
    the edges {i, j}, i < j, of the relabelled graph). Two graphs have equal
    forms iff they are isomorphic (with colors)."""
    lab, _ = canonical_labeling_lists(nbr, colors, stats, layers)
    return _form_of(nbr, lab, colors)


def canonical_form(X, colors=None, stats=None, layers="class"):
    """canonical_form_lists for an adjacency matrix."""
    return canonical_form_lists(_neighbours(X), colors, stats, layers)


def canon_iso_lists(nx, ny, colors_x=None, colors_y=None, stats=None):
    """Isomorphism test by canonical forms (same return value as
    gi.bounded.bounded_iso_lists): None, or (sigma, aut_gens of X) with
    sigma = lab_X then lab_Y^-1."""
    if len(nx) != len(ny):
        return None
    lx, gens = canonical_labeling_lists(nx, colors_x, stats)
    ly, _ = canonical_labeling_lists(ny, colors_y, stats)
    if _form_of(nx, lx, colors_x) != _form_of(ny, ly, colors_y):
        return None
    yi = [0] * len(ly)
    for v, l in enumerate(ly):
        yi[l] = v
    return tuple(yi[l] for l in lx), gens


def canon_iso(X, Y, colors_x=None, colors_y=None, stats=None):
    """canon_iso_lists for adjacency matrices."""
    return canon_iso_lists(_neighbours(X), _neighbours(Y), colors_x, colors_y, stats)
