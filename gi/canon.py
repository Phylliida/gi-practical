def _getter(t):
    """itemgetter(*t) returning a tuple also for len(t) == 1."""
    if len(t) == 1:
        a = t[0]
        return lambda x: (x[a],)
    return itemgetter(*t)


def _invariant(acts, x):
    """Whether x^g == x for every permutation g in acts."""
    for g in acts:
        if _getter(g)(x) != x:
            return False
    return True


def perm_canon(P, x, stats=None):
    """The least act(x, h) over h in the permutation group P (on positions
    0..m-1, read in this order), by depth-first search.

    Search over g = h^-1: the image string is s_g[p] = x[g[p]]. With the
    stabilizer chain of base 0, 1, ..., m-1, the node (l, t) is the set
    {s t : s in P^(l)} (P^(l) fixes 0..l-1), on which s_g[p] = s_t[p] for
    p < l; its children are (l+1, u t) for u = T[l][beta], beta in the orbit
    of l under P^(l), with s_(u t)[l] = s_t[beta]. Pruning (each keeps every
    least leaf up to the automorphisms found, so the search returns the least
    image and generators of all of Aut_P(x)):
      * value: children with a larger value at l than a sibling, and nodes
        whose prefix exceeds the best leaf's, contain no least leaf;
      * invariance: if s_t is invariant under P^(l), every leaf below has the
        string s_t; the node is a leaf, and t^-1 s t (s in P^(l)) are
        automorphisms of x;
      * automorphisms: a child whose image t[beta] lies in the orbit of an
        explored sibling's image under the known automorphisms fixing
        t[0..l-1] has the same subtree up to that automorphism.
    Two leaves g1, g2 with equal strings give the automorphism g1^-1 g2
    (x[a[q]] = x[q]). Every least leaf is equivalent under the automorphisms
    found to a visited least leaf (induction over the pruned tree), so they
    generate Aut_P(x).

    Returns (F, lam, gens): act(x, lam) == F (the least image), and gens
    generate Aut_P(F) = lam^-1 Aut_P(x) lam."""
    m = P.n
    x = tuple(x)
    gens = P.gens
    if not gens or _invariant(gens, x):
        return x, identity(m), list(gens)
    C = PermGroup(m, gens, base=range(m), order=P.order())
    T, S = C.T, C.S
    nt = [l for l in range(m) if len(T[l]) > 1]
    nlev = len(nt)
    idn = identity(m)
    best = [None, None]                 # least string so far, and its g
    auts, autset = [], set()
    nodes = [0]

    def add_aut(a):
        if a != idn and a not in autset:
            autset.add(a)
            auts.append(a)

    def leaf(t, y):
        if best[0] is None or y < best[0]:
            best[0], best[1] = y, t
        elif y == best[0]:
            add_aut(mul(inv(best[1]), t))

    def dfs(j, t):
        nodes[0] += 1
        y = _getter(t)(x)               # s_t
        l = nt[j] if j < nlev else m
        b = best[0]
        if b is not None and y[:l] > b[:l]:
            return
        if j == nlev:
            leaf(t, y)
            return
        Sl = S[l]
        for s in Sl:
            if _getter(s)(y) != y:
                break
        else:                           # s_t invariant under P^(l)
            ti = inv(t)
            for s in Sl:
                add_aut(mul(mul(ti, s), t))
            leaf(t, y)
            return
        Tl = T[l]
        mn = min(y[beta] for beta in Tl)
        kids = [beta for beta in Tl if y[beta] == mn]
        explored = []
        fixed = [t[q] for q in nt[:j]]
        for beta in kids:
            img = t[beta]
            if explored and auts:
                fix = [a for a in auts if all(a[p] == p for p in fixed)]
                if fix and _in_orbit(img, explored, fix):
                    continue
            dfs(j + 1, mul(Tl[beta], t))
            explored.append(img)

    dfs(0, idn)
    if stats is not None:
        stats["canon_perm_calls"] += 1
        stats["canon_perm_nodes"] += nodes[0]
        stats["canon_perm_max_degree"] = max(stats["canon_perm_max_degree"], m)
    F, bt = best
    lam = inv(bt)
    return F, lam, [mul(mul(bt, a), lam) for a in auts]


def _in_orbit(p, starts, gens):
    seen = set(starts)
    if p in seen:
        return True
    stack = list(starts)
    while stack:
        q = stack.pop()
        for a in gens:
            r = a[q]
            if r not in seen:
                if r == p:
                    return True
                seen.add(r)
                stack.append(r)
    return False


def _as_ea(G, n):
    """G as an EA2 if it is elementary abelian (a property of the group: its
    generators commute and are involutions), else None. PermGroup.gens is
    irredundant, hence a basis then."""
    if isinstance(G, EA2):
        return G
    if _ea_possible(G) and is_ea2(G.gens, n):
        return EA2(n, G.gens)
    return None


def _ea_possible(G):
    """A cheap necessary condition for a group with irredundant generators to be
    elementary abelian: its order is 2^(number of generators)."""
    return G.order() == 1 << len(G.gens)


class _LazyGroup:
    """A permutation group by a generating set (a list, equal to what PermGroup
    would keep of it) and its known order; the stabilizer chain (PermGroup) is
    only built when something needs it (real()). Enough for the layers of the
    canonizer where the string is invariant under the group."""
    __slots__ = ("n", "gens", "_order", "_pg")

    def __init__(self, n, gens, order):
        self.n, self.gens, self._order, self._pg = n, gens, order, None

    def order(self):
        return self._order

    def real(self):
        if self._pg is None:
            self._pg = PermGroup(self.n, self.gens, order=self._order)
        return self._pg


def _orbit_index(acts, m, deg):
    """orb[p] = the index of the orbit of position p under the permutations acts
    (of degree deg >= m, or None if there are none: every point its own orbit);
    only points below m are returned."""
    if deg is None:
        return None
    if _ck is not None:
        orbs = _ck.orbits(deg, acts)
        if orbs is not None:
            lab = [0] * deg
            for i, o in enumerate(orbs):
                for p in o:
                    lab[p] = i
            return lab
    lab = [-1] * deg
    nxt = 0
    for s in range(deg):
        if lab[s] >= 0:
            continue
        lab[s] = nxt
        stack = [s]
        while stack:
            q = stack.pop()
            for a in acts:
                r = a[q]
                if lab[r] < 0:
                    lab[r] = nxt
                    stack.append(r)
        nxt += 1
    return lab


def canon_group(G, n, pos, pidx, x, image, stats, tag="", acts=None):
    """Canonize the string x on the positions pos (ordered; pidx: position ->
    index) under the action of G (an EA2 or PermGroup on range(n)), where
    image(g, p) is the image of position p under g. Returns (a, U): a in G
    (None for the identity) with act(x, a) the canonical form, and U =
    Aut_G(act(x, a)) (an EA2 when elementary abelian, else a PermGroup).
    acts, when given, is the action of each generator on the positions (a list
    parallel to G.gens), already computed by the caller's closure."""
    gens = G.gens
    if not gens:
        stats["canon_trivial"] += 1
        return None, G
    if acts is None:
        acts = [tuple([pidx[image(g, p)] for p in pos]) for g in gens]
    x = tuple(x)
    if _invariant(acts, x):
        stats["canon_invariant"] += 1
        return None, G
    E = _as_ea(G, n)
    if isinstance(G, _LazyGroup):       # (from here on a stabilizer chain is needed)
        G = G.real()
        gens = G.gens
    if E is not None:
        stats["canon_ea" + tag] += 1
        c, N = EAAction(len(E.gens), acts, len(pos)).canon(x)
        return (E.elem(c) if c else None), EA2(n, [E.elem(v) for v in N])
    stats["canon_perm" + tag] += 1
    phi = ActionHom(G, len(pos), lambda g: tuple([pidx[image(g, p)] for p in pos]))
    P = phi.image_group()
    _, lamP, autsP = perm_canon(P, x, stats)
    a = phi.lift(lamP)
    K = phi.kernel()
    order = (PermGroup(len(pos), autsP).order() if autsP else 1) * K.order()
    U = PermGroup(n, [phi.lift(h) for h in autsP] + list(K.gens), order=order)
    return (None if a == identity(n) else a), (_as_ea(U, n) or U)


def ir_canon(adj, col0):
    """Canonical labelling of a vertex-colored graph on range(n) (neighbour
    lists adj, colors col0) under the color-preserving permutations, by
    individualization-refinement search (gi.wl.refine, automorphism pruning at
    the search nodes). A leaf is a discrete coloring; its labelling sends
    each color class of col0 onto itself, ordered by the leaf's cells, so the
    labelling is a function of (adj, col0) up to the color-preserving
    automorphisms; the canonical labelling is one minimizing the relabelled
    sorted edge list. Returns (lab, auts): lab[v] is the new name of v (a
    permutation inside each class of col0), and auts generate the automorphism
    group of (adj, col0) (every least leaf is mapped to a visited one by the
    found automorphisms: induction over the pruned tree, and the visited least
    leaves are all compared with the first). Exponential in the worst case,
    exact always."""
    n = len(adj)
    classes = {}
    for v in range(n):
        classes.setdefault(col0[v], []).append(v)
    base = {}
    for c0, vs in classes.items():      # vertices of the class by increasing name
        base[c0] = sorted(vs)
    best = [None, None]
    auts = []
    nodes = [0]

    def labelling(c):
        """lab from a discrete coloring c: each class of col0 ordered by c."""
        lab = [0] * n
        for c0, vs in classes.items():
            order = sorted(vs, key=lambda v: c[v])
            for name, v in zip(base[c0], order):
                lab[v] = name
        return lab

    def search(c, path):
        nodes[0] += 1
        cells = {}
        for v in range(n):
            cells.setdefault(c[v], []).append(v)
        target = None
        for i in sorted(cells):
            if len(cells[i]) > 1:
                target = cells[i]
                break
        if target is None:
            lab = labelling(c)
            cert = tuple(sorted((min(lab[u], lab[v]), max(lab[u], lab[v]))
                                for u in range(n) for v in adj[u] if u < v))
            if best[0] is None or cert < best[0]:
                best[0], best[1] = cert, lab
            elif cert == best[0]:
                binv = [0] * n
                for v, l in enumerate(best[1]):
                    binv[l] = v
                a = tuple(binv[lab[v]] for v in range(n))
                if any(a[v] != v for v in range(n)) and a not in auts:
                    auts.append(a)
            return
        explored = []
        for v in target:
            if explored and auts:
                fix = [a for a in auts if all(a[p] == p for p in path)]
                if fix and _in_orbit(v, explored, fix):
                    continue
            search(wl_refine(adj, c, (v,), True), path + [v])
            explored.append(v)

    search(wl_refine(adj, col0), [])
    return best[1], auts


def canon_sparse(G, pos, table, x, stats, tag):
    """canon_group for an elementary abelian G given by a SparseEA: the same
    least image over the group. table is the action of the generators moving
    some point of a position on the positions: {generator id: {position
    index: its image, for the positions it moves}} (from _closure_sparse;
    generators moving no point of a position act trivially, so only these
    enter the linear algebra). Returns (a, restricted): a is the sparse element
    (a dict, or None for the identity) with act(x, a) the canonical form, and
    restricted says whether G was restricted in place to Aut_G(act(x, a))
    (Aut_G(x) = Aut_G(F): G is abelian); otherwise x is invariant and G
    unchanged."""
    if not table:
        stats["canon_trivial"] += 1
        return None, False
    for mv in table.values():           # x invariant under every generator?
        for p, q in mv.items():
            if x[p] != x[q]:
                break
        else:
            continue
        break
    else:
        stats["canon_invariant"] += 1
        return None, False
    x = tuple(x)
    gens = G.gens
    ids = sorted(table)
    m = len(pos)
    acts = []
    for gid in ids:
        a = list(range(m))
        for p, q in table[gid].items():
            a[p] = q
        acts.append(tuple(a))
    stats["canon_ea" + tag] += 1
    c, N = EAAction(len(ids), acts, m).canon(x)
    ds = []
    u = c
    while u:
        b = u & -u
        ds.append(gens[ids[b.bit_length() - 1]])
        u ^= b
    a = compose(ds) if c else None
    G.restrict(ids, N)
    return a, True


def _closure_sparse(seeds, G, image):
    """The closure of the positions seeds under the SparseEA G: (S_list, table),
    S_list = seeds (in order) followed by their images (in BFS order), table =
    {generator id: {i: j}}: the generator moves position S_list[i] to
    S_list[j], for the positions it moves (a generator moving a point of some
    position, but no position, has an empty dict)."""
    S_list = list(seeds)
    index = {S: i for i, S in enumerate(S_list)}
    gens, who = G.gens, G.who
    table = {}
    for i, S in enumerate(S_list):      # (the list grows: a BFS over the orbits)
        ids = set()
        for p in S:
            w = who.get(p)
            if w:
                ids.update(w)
        for gid in ids:
            S2 = image(gens[gid], S)
            j = index.get(S2)
            if j is None:
                j = index[S2] = len(S_list)
                S_list.append(S2)
            t = table.get(gid)
            if t is None:
                t = table[gid] = {}
            if j != i:
                t[i] = j
    return S_list, table


def _closure_dense(seeds, gens, image):
    """The closure of the positions seeds under the permutations gens:
    (S_list, rows), S_list = seeds followed by their images, rows[g][i] = the
    index in S_list of the image of S_list[i] under gens[g]."""
    S_list = list(seeds)
    index = {S: i for i, S in enumerate(S_list)}
    rows = [[] for _ in gens]
    for i, S in enumerate(S_list):
        for gi, g in enumerate(gens):
            S2 = image(g, S)
            j = index.get(S2)
            if j is None:
                j = index[S2] = len(S_list)
                S_list.append(S2)
            rows[gi].append(j)
    return S_list, rows


def _table_to_pos(table, S_list, pidx):
    """The closure table moved to position indices (pidx: position -> index)."""
    to = [pidx[S] for S in S_list]
    return {gid: {to[i]: to[j] for i, j in mv.items()} for gid, mv in table.items()}


def _rows_to_pos(rows, S_list, pidx):
    """The dense closure rows moved to position indices: for each generator
    a tuple, acts[g][p] = the index of the image of position p."""
    to = [pidx[S] for S in S_list]
    m = len(S_list)
    out = []
    for img in rows:
        a = [0] * m
        for i, j in enumerate(img):
            a[to[i]] = to[j]
        out.append(tuple(a))
    return out


def _set_image(g, S):
    return frozenset([g[i] for i in S])


def _set_image_sparse(g, S):
    return frozenset([g.get(i, i) for i in S])


def _pair_image_sparse(g, e):
    p, q = g.get(e[0], e[0]), g.get(e[1], e[1])
    return (p, q) if p < q else (q, p)


def _as_sparse_ea(G, n):
    """G as a SparseEA if it is elementary abelian, else None."""
    if isinstance(G, SparseEA):
        return G
    E = _as_ea(G, n)
    return None if E is None else SparseEA.from_tuples(E.gens)


def _pair_image(g, e):
    p, q = g[e[0]], g[e[1]]
    return (p, q) if p < q else (q, p)


