class NotSimple(ValueError):
    pass


# -- graphs -------------------------------------------------------------------
class _Graph:
    """A vertex-colored simple graph: nbr[v] sorted neighbour lists."""
    __slots__ = ("n", "nbr", "col")

    def __init__(self, nbr, col):
        self.n, self.nbr, self.col = len(nbr), nbr, col


def _neighbours(A):
    n = len(A)
    nbr = []
    for i in range(n):
        if A[i][i]:
            raise NotSimple("loops are not supported")
        row = []
        for j in range(n):
            if A[i][j]:
                if not A[j][i]:
                    raise NotSimple("directed graphs are not supported")
                row.append(j)
        nbr.append(row)
    return nbr


def _joint_names(cx, cy):
    vals = set(cx) | set(cy)
    try:
        srt = sorted(vals)
    except TypeError:
        srt = sorted(vals, key=repr)
    rank = {v: i for i, v in enumerate(srt)}
    return [rank[c] for c in cx], [rank[c] for c in cy]


def refine_1wl(nx, ny, cx, cy):
    """Joint color refinement of two graphs (neighbour lists nx, ny, int
    colors cx, cy). New colors are ranks of (old color, sorted neighbour
    colors) in the union of both graphs' signatures, so every isomorphism
    maps the refined x-colors onto the refined y-colors. None if the color
    histograms differ."""
    k = len(set(cx) | set(cy))
    while True:
        if Counter(cx) != Counter(cy):
            return None
        sx = [(cx[v], tuple(sorted(cx[w] for w in nx[v]))) for v in range(len(nx))]
        sy = [(cy[v], tuple(sorted(cy[w] for w in ny[v]))) for v in range(len(ny))]
        cx, cy = _joint_names(sx, sy)
        k2 = len(set(cx) | set(cy))
        if k2 == k:
            return (cx, cy) if Counter(cx) == Counter(cy) else None
        k = k2


def _components(nbr):
    n = len(nbr)
    comp = [-1] * n
    out = []
    for s in range(n):
        if comp[s] >= 0:
            continue
        comp[s] = len(out)
        part = [s]
        for v in part:
            for w in nbr[v]:
                if comp[w] < 0:
                    comp[w] = comp[s]
                    part.append(w)
        out.append(sorted(part))
    return out


def _induced(g, part):
    loc = {v: i for i, v in enumerate(part)}
    return _Graph([[loc[w] for w in g.nbr[v]] for v in part], [g.col[v] for v in part])


# -- the layered structure from an oriented edge ---------------------------------
class _Rooted:
    """BFS layers of a connected graph from the oriented edge (u0, u1).
    Vertices are renumbered by layers: order[i] is the vertex of index i,
    start[r] the first index of layer r (start[-1] = n). up[i] is the set of
    indices of the neighbours of index i in the previous layer, adj[i] the set
    of all neighbour indices, col[i] the color. The attachment classes of
    layer r + 1 (index sets up[t] -> sorted members) are cached per r."""
    __slots__ = ("order", "start", "up", "adj", "col", "_att", "_inner")

    def __init__(self, g, u0, u1):
        n = g.n
        dist = [-1] * n
        dist[u0] = dist[u1] = 0
        order = [u0, u1]
        start = [0, 2]
        cur = order[:]
        while True:
            nxt = []
            for v in cur:
                for w in g.nbr[v]:
                    if dist[w] < 0:
                        dist[w] = dist[v] + 1
                        nxt.append(w)
            if not nxt:
                break
            order.extend(nxt)
            start.append(len(order))
            cur = nxt
        if len(order) != n:
            raise ValueError("graph is not connected")
        pos = [0] * n
        for i, v in enumerate(order):
            pos[v] = i
        self.order, self.start = order, start
        self.adj = [frozenset(pos[w] for w in g.nbr[v]) for v in order]
        self.col = [g.col[v] for v in order]
        self.up = [frozenset(pos[w] for w in g.nbr[v] if dist[w] == dist[v] - 1) for v in order]
        self._att = {}
        self._inner = {}

    def attachments(self, r):
        """{up-set: members of layer r + 1 with that up-set, sorted by (color,
        index)} (the twin classes over layer r)."""
        a = self._att.get(r)
        if a is None:
            a = {}
            for t in range(self.start[r + 1], self.start[r + 2]):
                a.setdefault(self.up[t], []).append(t)
            col = self.col
            for ts in a.values():
                ts.sort(key=lambda t: (col[t], t))
            self._att[r] = a
        return a

    def inner_edges(self, r):
        """The number of edges inside layer r + 1."""
        e = self._inner.get(r)
        if e is None:
            b, c = self.start[r + 1], self.start[r + 2]
            e = self._inner[r] = sum(1 for t in range(b, c) for u in self.adj[t] if t < u < c)
        return e


class _Layer:
    """The X-side data of one step (see _Chain.step)."""
    __slots__ = ("r", "a", "b", "c", "A", "aidx", "T", "slot", "S", "sidx", "xS", "phi1", "P1",
                 "Gpp", "rho", "gens2", "order2", "H2", "x2", "pairs", "pidx", "kernel_ext")


class _Chain:
    """The groups G_r = Aut_f(X_r) of one rooted graph X (built lazily, as far
    as some target got) and the isomorphism cosets towards targets."""

    def __init__(self, X, solver):
        self.X, self.solver = X, solver
        self.G = [PermGroup(2)]         # G[r] = G_r on range(start[r + 1])
        self.L = []                     # L[r] = _Layer of step r
        self.codes = {(): 0}            # color multisets of twin classes -> ints

    def steps(self):
        return len(self.X.start) - 2

    def code(self, t):
        c = self.codes.get(t)
        if c is None:
            c = self.codes[t] = len(self.codes)
        return c

    def run(self, Z):
        """sigma (index map X -> Z, an isomorphism of the rooted graphs) or
        None. Every step is exact, so None means no isomorphism maps the root
        of X to the root of Z."""
        X = self.X
        st = self.solver.stats
        st["luks_runs"] += 1
        if Z.start != X.start or Z.col[0] != X.col[0] or Z.col[1] != X.col[1]:
            return None
        sigma = (0, 1)
        for r in range(self.steps()):
            st["luks_steps"] += 1
            sigma = self.step(r, Z, sigma)
            if sigma is None:
                return None
        return sigma

    # -- phase 1: attachment sets under G_r ---------------------------------------
    def layer1(self, r):
        if len(self.L) > r:
            return self.L[r]
        X, st = self.X, self.solver.stats
        G = self.G[r]
        L = _Layer()
        L.r, L.Gpp = r, None
        L.a, L.b, L.c = X.start[r], X.start[r + 1], X.start[r + 2]
        att = X.attachments(r)
        L.A = list(att)                 # the attachment sets of X (in order of t)
        L.aidx = {S: s for s, S in enumerate(L.A)}
        L.T = att
        L.slot = {}                     # t -> (index of its set, rank in its class)
        for s, S in enumerate(L.A):
            for k, t in enumerate(att[S]):
                L.slot[t] = (s, k)
        # positions: the G_r-orbits of the attachment sets of X
        S_list = list(L.A)
        sidx = dict(L.aidx)
        for S in S_list:                # (the list grows: a BFS over the orbits)
            for g in G.gens:
                S2 = frozenset(g[i] for i in S)
                if S2 not in sidx:
                    sidx[S2] = len(S_list)
                    S_list.append(S2)
        L.S, L.sidx = S_list, sidx
        xS = [0] * len(S_list)
        for s, S in enumerate(L.A):
            xS[s] = self.code(tuple(X.col[t] for t in att[S]))
        L.xS = tuple(xS)
        if G.gens:
            m = len(S_list)
            L.phi1 = ActionHom(G, m, lambda g: tuple(sidx[frozenset(g[i] for i in S)] for S in S_list))
            L.P1 = L.phi1.image_group()
        else:
            L.phi1 = L.P1 = None
        st["luks_phase1_max_degree"] = max(st["luks_phase1_max_degree"], len(S_list))
        self.L.append(L)
        return L

    # -- phase 2: twin classes and edges inside layer r + 1 ---------------------------
    def layer2(self, L):
        X, st = self.X, self.solver.stats
        Gpp, b, c = L.Gpp, L.b, L.c
        nV, nA = c - b, len(L.A)
        A, aidx, T, slot = L.A, L.aidx, L.T, L.slot
        if Gpp.gens:
            L.rho = ActionHom(Gpp, nA, lambda g: tuple(aidx[frozenset(g[i] for i in S)] for S in A))
            rho_order = L.rho.image_order()
        else:
            L.rho, rho_order = None, 1
        gens = []
        idV = identity(nV)
        if L.rho is not None:
            for g in Gpp.gens:
                p = L.rho.image_of(g)
                h = tuple(T[A[p[slot[t][0]]]][slot[t][1]] - b for t in range(b, c))
                if h != idV:
                    gens.append(h)
        order = rho_order
        col = X.col
        for S in A:                     # Sym of each color class of each twin class
            ts = T[S]
            i = 0
            while i < len(ts):
                j = i
                while j < len(ts) and col[ts[j]] == col[ts[i]]:
                    j += 1
                if j - i >= 2:
                    gens.extend(sym_gens(nV, [t - b for t in ts[i:j]]))
                    order *= math.factorial(j - i)
                i = j
        L.gens2, L.order2 = gens, order
        st["luks_twin_max"] = max([st["luks_twin_max"]] + [len(ts) for ts in T.values()])
        st["luks_phase2_max_log2_order"] = max(st["luks_phase2_max_log2_order"],
                                               round(math.log2(order)))
        kern = L.rho.kernel().gens if L.rho is not None else []
        L.kernel_ext = [tuple(k) + tuple(range(b, c)) for k in kern]
        L.H2 = None
        if not X.inner_edges(L.r):
            return
        # pairs: the orbits of the edges inside layer r + 1 (as index pairs of
        # the layer's vertices) under the group generated by gens
        pairs, pidx = [], {}
        for t in range(b, c):
            for u in X.adj[t]:
                if t < u < c:
                    pidx[(t - b, u - b)] = nV + len(pairs)
                    pairs.append((t - b, u - b))
        ne = len(pairs)
        for p, q in pairs:
            for h in gens:
                hp, hq = h[p], h[q]
                pq = (hp, hq) if hp < hq else (hq, hp)
                if pq not in pidx:
                    pidx[pq] = nV + len(pairs)
                    pairs.append(pq)
        L.pairs, L.pidx = pairs, pidx
        M = nV + len(pairs)
        gensD = []
        for h in gens:
            img = list(h)
            for p, q in pairs:
                hp, hq = h[p], h[q]
                img.append(pidx[(hp, hq) if hp < hq else (hq, hp)])
            gensD.append(tuple(img))
        L.H2 = PermGroup(M, gensD, order=order)
        L.x2 = tuple([0] * nV + [1] * ne + [0] * (len(pairs) - ne))
        st["luks_phase2_max_degree"] = max(st["luks_phase2_max_degree"], M)

    def step(self, r, Z, sigma):
        X, S = self.X, self.solver
        L = self.layer1(r)
        b, c = L.b, L.c
        # (1) attachment sets of Z, pulled back to X's indices by sigma
        sinv = [0] * b
        for i, j in enumerate(sigma):
            sinv[j] = i
        attZ = Z.attachments(r)
        yS = [0] * len(L.S)
        for SZ, ts in attZ.items():
            s = L.sidx.get(frozenset(sinv[j] for j in SZ))
            if s is None:               # x is 0 on the whole G_r-orbit closure
                return None
            yS[s] = self.code(tuple(Z.col[t] for t in ts))
        yS = tuple(yS)
        first = L.Gpp is None
        if L.P1 is None:
            if yS != L.xS:
                return None
            rep = None
            if first:
                L.Gpp = self.G[r]
        else:
            res = S.solve(L.P1, range(len(L.S)), L.xS, yS)
            if res is None:
                return None
            if first:
                phi = L.phi1
                L.Gpp = PermGroup(b, [phi.lift(h) for h in res.gens] + phi.kernel().gens,
                                  ambient_base=self.G[r].short_base())
            rep = L.phi1.lift(res.rep)
        if rep is not None:
            sigma = mul(rep, sigma)
        if first:
            self.layer2(L)
        # (2) psi: X's twin classes onto Z's (by rank: colors agree after (1))
        psi = [0] * (c - b)
        for Sx, ts in L.T.items():
            tz = attZ.get(frozenset(sigma[i] for i in Sx))
            if tz is None or len(tz) != len(ts):
                raise AssertionError("phase 1 left twin classes unmatched")
            for t, u in zip(ts, tz):
                psi[t - b] = u
        if L.H2 is None:
            if Z.inner_edges(r):
                return None
            h0, auts = None, L.gens2
        else:
            pairs, nV = L.pairs, c - b
            y2 = [0] * len(L.x2)
            ones = 0
            for j, (p, q) in enumerate(pairs):
                if psi[q] in Z.adj[psi[p]]:
                    y2[nV + j] = 1
                    ones += 1
            if ones != Z.inner_edges(r):  # an edge of Z outside the positions
                return None
            res = S.solve(L.H2, range(len(y2)), L.x2, tuple(y2))
            if res is None:
                return None
            h0, auts = res.rep, res.gens
        if len(self.G) == r + 1:
            G1 = PermGroup(c, [self.extend(L, h) for h in auts] + L.kernel_ext)
            self.G.append(G1)
            st = S.stats
            st["luks_group_max_log2_order"] = max(st["luks_group_max_log2_order"],
                                                  round(math.log2(G1.order())))
        if h0 is None:
            return tuple(sigma) + tuple(psi)
        g0 = self.lift2(L, h0)
        return tuple(mul(g0, sigma)) + tuple(psi[h0[t - b]] for t in range(b, c))

    def lift2(self, L, h):
        """g in G'' inducing on the attachment sets of X what h (a permutation
        of layer r + 1, in the phase-2 group) induces."""
        if L.rho is None:
            return identity(L.b)
        b, T, A, slot = L.b, L.T, L.A, L.slot
        p = tuple(slot[b + h[T[S][0] - b]][0] for S in A)
        return L.rho.lift(p)

    def extend(self, L, h):
        """g+ for h in Aut_H2(x2): an element of G_{r+1}."""
        b = L.b
        return tuple(self.lift2(L, h)) + tuple(b + h[t] for t in range(L.c - b))

    def aut(self):
        """Generators of G_R = Aut_f(X) as index permutations (the chain must
        be complete)."""
        assert len(self.G) == self.steps() + 1
        return list(self.G[-1].gens)


# -- connected graphs -------------------------------------------------------------
class _Connected:
    """A connected graph with its oriented-edge invariants; with aut=True also
    Aut(X), the orbits of Aut(X) on oriented edges and the chains used."""

    def __init__(self, g, solver, aut=True, root="class"):
        self.g, self.solver, self.root = g, solver, root
        n = g.n
        self.edges = [(u, v) for u in range(n) for v in g.nbr[u]]
        self.eidx = {e: i for i, e in enumerate(self.edges)}
        self.invs = self.invariants()
        self.chains = {}
        self.gens = None
        if aut and self.edges:
            self.compute_aut()

    def invariants(self):
        g = self.g
        n = g.n
        dist = []
        for s in range(n):
            d = [-1] * n
            d[s] = 0
            q = [s]
            for v in q:
                for w in g.nbr[v]:
                    if d[w] < 0:
                        d[w] = d[v] + 1
                        q.append(w)
            dist.append(d)
        K = n + 1
        C = 1 + max(g.col, default=0)
        out = []
        for u, v in self.edges:
            du, dv = dist[u], dist[v]
            cnt = Counter((du[w] * K + dv[w]) * C + g.col[w] for w in range(n))
            out.append((g.col[u], g.col[v], tuple(sorted(cnt.items()))))
        return out

    def rooted(self, f):
        return _Rooted(self.g, *self.edges[f])

    def chain(self, f):
        c = self.chains.get(f)
        if c is None:
            c = self.chains[f] = _Chain(self.rooted(f), self.solver)
        return c

    def vertex_map(self, X, Z, sigma):
        out = [0] * len(sigma)
        for i, s in enumerate(sigma):
            out[X.order[i]] = Z.order[s]
        return tuple(out)

    def compute_aut(self):
        cls = Counter(self.invs)
        if self.root == "degree":       # an edge between two vertices of maximum degree sum
            deg = [len(x) for x in self.g.nbr]
            f0 = min(range(len(self.edges)), key=lambda i: (
                -deg[self.edges[i][0]] - deg[self.edges[i][1]], cls[self.invs[i]], i))
        else:                           # the smallest invariant class (fewest tests)
            f0 = min(range(len(self.edges)), key=lambda i: (cls[self.invs[i]], i))
        self.f0 = f0
        ch = self.chain(f0)
        X = ch.X
        if ch.run(X) is None:           # (X, f0) -> (X, f0) always exists
            raise AssertionError("no automorphism found for the root")
        gens = [self.vertex_map(X, X, g) for g in ch.aut()]
        parent = list(range(len(self.edges)))

        def find(v):
            while parent[v] != v:
                parent[v] = parent[parent[v]]
                v = parent[v]
            return v

        def absorb(g):
            for i, (u, v) in enumerate(self.edges):
                a, b = find(i), find(self.eidx[(g[u], g[v])])
                if a != b:
                    parent[max(a, b)] = min(a, b)

        for g in gens:
            absorb(g)
        failed = []
        inv0 = self.invs[f0]
        for f in range(len(self.edges)):
            if f == f0 or self.invs[f] != inv0:
                continue
            rf = find(f)
            if rf == find(f0) or any(find(e) == rf for e in failed):
                continue
            self.solver.stats["luks_aut_tests"] += 1
            Z = self.rooted(f)
            s = ch.run(Z)
            if s is None:
                failed.append(f)
                continue
            g = self.vertex_map(X, Z, s)
            gens.append(g)
            absorb(g)
        self.gens = gens
        self.find = find

    def iso(self, other):
        """A vertex map self -> other (connected, same color names), or None."""
        if self.g.n != other.g.n or len(self.edges) != len(other.edges):
            return None
        if Counter(self.invs) != Counter(other.invs):
            return None
        inv0 = self.invs[self.f0]
        e1 = next(i for i, v in enumerate(other.invs) if v == inv0)
        Z = other.rooted(e1)
        reps, seen = [self.f0], {self.find(self.f0)}
        for f in range(len(self.edges)):
            if self.invs[f] == inv0 and self.find(f) not in seen:
                seen.add(self.find(f))
                reps.append(f)
        for f in reps:
            self.solver.stats["luks_iso_tests"] += 1
            ch = self.chain(f)
            s = ch.run(Z)
            if s is not None:
                return self.vertex_map(ch.X, Z, s)
        return None


def _invert(p):
    r = [0] * len(p)
    for i, j in enumerate(p):
        r[j] = i
    return r


def bounded_iso(X, Y, solver=None, vcolors_x=None, vcolors_y=None, refine=True, root="class"):
    """X, Y: adjacency matrices of undirected loopless graphs (any degree; the
    groups have composition factors in Sym(d - 1) for maximum degree d).
    Returns None if not isomorphic, else (sigma, aut_gens): sigma[i] is the
    image of vertex i (an isomorphism X -> Y) and aut_gens generate Aut(X)
    (vertex colors respected). solver: a Solver (default
    Solver(cameron_no_enum=True)); its stats count the reduction's work
    (luks_*). root: how the root edge f0 of each component is chosen,
    "class" (smallest invariant class, the fewest tests) or "degree" (an edge
    of maximum degree sum, which makes large twin classes appear early); it
    only changes the running time and which generators are returned."""
    n = len(X)
    if len(Y) != n:
        return None
    if n == 0:
        return (), []
    solver = solver or Solver(cameron_no_enum=True)
    nx, ny = _neighbours(X), _neighbours(Y)
    cx, cy = _joint_names(vcolors_x or [0] * n, vcolors_y or [0] * n)
    if refine:
        r = refine_1wl(nx, ny, cx, cy)
        if r is None:
            solver.stats["luks_refine_reject"] += 1
            return None
        cx, cy = r
    elif Counter(cx) != Counter(cy):
        return None
    if sorted(map(len, nx)) != sorted(map(len, ny)):
        return None
    gx, gy = _Graph(nx, cx), _Graph(ny, cy)
    px, py = _components(nx), _components(ny)
    if len(px) != len(py):
        return None

    def key(g, part):
        return (len(part), sum(len(g.nbr[v]) for v in part), tuple(sorted(g.col[v] for v in part)))

    # isomorphism classes of X's components: [rep, [(part, iso rep -> part)], key]
    classes = []
    for part in px:
        k = key(gx, part)
        sub = _induced(gx, part)
        for C in classes:
            if C[2] == k:
                t = _component_iso(C[0], sub, solver)
                if t is not None:
                    C[1].append((part, t))
                    break
        else:
            rep = _Connected(sub, solver, root=root) if len(part) > 1 else _Single(sub)
            classes.append([rep, [(part, tuple(range(len(part))))], k])
    matches = [[] for _ in classes]
    for part in py:
        k = key(gy, part)
        sub = _induced(gy, part)
        for ci, C in enumerate(classes):
            if C[2] == k and len(matches[ci]) < len(C[1]):
                t = _component_iso(C[0], sub, solver)
                if t is not None:
                    matches[ci].append((part, t))
                    break
        else:
            return None
    sigma = [0] * n
    gens = []
    for C, M in zip(classes, matches):
        if len(M) != len(C[1]):
            return None
        rep, members = C[0], C[1]
        p1 = members[0][0]
        for g in rep.gens:              # Aut of the representative component
            h = list(range(n))
            for i, v in enumerate(p1):
                h[v] = p1[g[i]]
            gens.append(tuple(h))
        for (part, t), (ypart, s) in zip(members, M):
            ti = _invert(t)
            for i, v in enumerate(part):        # part -> rep -> ypart
                sigma[v] = ypart[s[ti[i]]]
        for part, t in members[1:]:     # swaps of the representative with each copy
            h = list(range(n))
            for i, v in enumerate(p1):
                h[v] = part[t[i]]
                h[part[t[i]]] = v
            gens.append(tuple(h))
    idn = identity(n)
    return tuple(sigma), [g for g in dict.fromkeys(gens) if g != idn]


class _Single:
    """A one-vertex component."""
    gens = ()

    def __init__(self, g):
        self.g = g


def _component_iso(rep, sub, solver):
    """A vertex map rep -> sub (connected graphs of equal size, edge count and
    color multiset), or None."""
    if isinstance(rep, _Single):
        return (0,) if rep.g.col == sub.col else None
    return rep.iso(_Connected(sub, solver, aut=False))
