_FALLBACK = object()


class _Chain:
    """The groups G_r = Aut_f(X_r) of one rooted graph X (built lazily, as far
    as some target got) and the isomorphism cosets towards targets."""

    def __init__(self, X, solver, ea=True, plan=None):
        self.X, self.solver, self.ea, self.plan = X, solver, ea, plan
        # G[r] = G_r on range(start[r + 1]): a PermGroup, or None while it is
        # elementary abelian and ea is on: then the group of the newest
        # stage is self.cur (a SparseEA advanced in place, generators extended
        # to new points), and older stages live on in the layers' data
        self.G = [None if ea else PermGroup(2)]
        self.cur = SparseEA()
        self.L = []                     # L[r] = _Layer of step r
        self.codes = {(): 0}            # color multisets of twin classes -> ints
        self.hist = None                # color histogram of X

    def steps(self):
        return len(self.X.start) - 2

    def code(self, t):
        c = self.codes.get(t)
        if c is None:
            c = self.codes[t] = len(self.codes)
        return c

    def target(self, seed):
        """The seed layered by this chain's plan (cached on the seed)."""
        key = id(self.plan)
        Z = seed.layered.get(key)
        if Z is None or Z[0] is not self.plan:
            Z = seed.layered[key] = (self.plan, _Rooted(seed.g, seed.u0, seed.u1, seed.col,
                                                        self.plan))
        return Z[1]

    def run(self, Z):
        """sigma (index map X -> Z, an isomorphism of the rooted graphs) or
        None. Every step is exact, so None means no isomorphism maps the root
        of X to the root of Z."""
        X = self.X
        st = self.solver.stats
        st["luks_runs"] += 1
        if not Z.ok or Z.start != X.start or Z.col[0] != X.col[0] or Z.col[1] != X.col[1]:
            return None
        if self.hist is None:
            self.hist = Counter(X.col)
        if Counter(Z.col) != self.hist:
            return None
        sigma, sinv = [0, 1], [0, 1]    # the coset representative and its inverse
        for r in range(self.steps()):
            st["luks_steps"] += 1
            if not self.step(r, Z, sigma, sinv):
                return None
        return tuple(sigma)

    # -- phase 1: attachment sets under G_r ---------------------------------------
    def layer1(self, r):
        if len(self.L) > r:
            return self.L[r]
        X, st = self.X, self.solver.stats
        G = self.G[r]
        L = _Layer()
        L.r, L.Gpp = r, None
        L.a, L.b, L.c = X.start[r], X.start[r + 1], X.start[r + 2]
        att = X.attachments(r)
        L.A = list(att)                 # the attachment sets of X (in order of t)
        L.aidx = {S: s for s, S in enumerate(L.A)}
        L.T = att
        L.slot = {}                     # t -> (index of its set, rank in its class)
        for s, S in enumerate(L.A):
            for k, t in enumerate(att[S]):
                L.slot[t] = (s, k)
        # positions: the G_r-orbits of the attachment sets of X
        S_list = list(L.A)
        sidx = dict(L.aidx)
        for S in S_list:                # (the list grows: a BFS over the orbits)
            for g in G.gens:
                S2 = frozenset(g[i] for i in S)
                if S2 not in sidx:
                    sidx[S2] = len(S_list)
                    S_list.append(S2)
        L.S, L.sidx = S_list, sidx
        xS = [0] * len(S_list)
        for s, S in enumerate(L.A):
            xS[s] = self.code(tuple(X.col[t] for t in att[S]))
        L.xS = tuple(xS)
        if G.gens:
            m = len(S_list)
            L.phi1 = ActionHom(G, m, lambda g: tuple(sidx[frozenset(g[i] for i in S)] for S in S_list))
            L.P1 = L.phi1.image_group()
        else:
            L.phi1 = L.P1 = None
        st["luks_phase1_max_degree"] = max(st["luks_phase1_max_degree"], len(S_list))
        self.L.append(L)
        return L

    # -- phase 2: twin classes and edges inside layer r + 1 ---------------------------
    def layer2(self, L):
        X, st = self.X, self.solver.stats
        Gpp, b, c = L.Gpp, L.b, L.c
        nV, nA = c - b, len(L.A)
        A, aidx, T, slot = L.A, L.aidx, L.T, L.slot
        if Gpp.gens:
            L.rho = ActionHom(Gpp, nA, lambda g: tuple(aidx[frozenset(g[i] for i in S)] for S in A))
            rho_order = L.rho.image_order()
        else:
            L.rho, rho_order = None, 1
        gens = []
        idV = identity(nV)
        if L.rho is not None:
            for g in Gpp.gens:
                p = L.rho.image_of(g)
                h = tuple(T[A[p[slot[t][0]]]][slot[t][1]] - b for t in range(b, c))
                if h != idV:
                    gens.append(h)
        order = rho_order
        col = X.col
        for S in A:                     # Sym of each color class of each twin class
            ts = T[S]
            i = 0
            while i < len(ts):
                j = i
                while j < len(ts) and col[ts[j]] == col[ts[i]]:
                    j += 1
                if j - i >= 2:
                    gens.extend(sym_gens(nV, [t - b for t in ts[i:j]]))
                    order *= math.factorial(j - i)
                i = j
        L.gens2, L.order2 = gens, order
        st["luks_twin_max"] = max([st["luks_twin_max"]] + [len(ts) for ts in T.values()])
        st["luks_phase2_max_log2_order"] = max(st["luks_phase2_max_log2_order"],
                                               round(math.log2(order)))
        kern = L.rho.kernel().gens if L.rho is not None else []
        L.kernel_ext = [tuple(k) + tuple(range(b, c)) for k in kern]
        L.H2 = None
        if not X.inner_edges(L.r):
            return
        # pairs: the orbits of the edges inside layer r + 1 (as index pairs of
        # the layer's vertices) under the group generated by gens
        pairs, pidx = [], {}
        for t in range(b, c):
            for u in X.adj[t]:
                if t < u < c:
                    pidx[(t - b, u - b)] = nV + len(pairs)
                    pairs.append((t - b, u - b))
        ne = len(pairs)
        for p, q in pairs:
            for h in gens:
                hp, hq = h[p], h[q]
                pq = (hp, hq) if hp < hq else (hq, hp)
                if pq not in pidx:
                    pidx[pq] = nV + len(pairs)
                    pairs.append(pq)
        L.pairs, L.pidx = pairs, pidx
        M = nV + len(pairs)
        gensD = []
        for h in gens:
            img = list(h)
            for p, q in pairs:
                hp, hq = h[p], h[q]
                img.append(pidx[(hp, hq) if hp < hq else (hq, hp)])
            gensD.append(tuple(img))
        L.H2 = PermGroup(M, gensD, order=order)
        L.x2 = tuple([0] * nV + [1] * ne + [0] * (len(pairs) - ne))
        st["luks_phase2_max_degree"] = max(st["luks_phase2_max_degree"], M)

    def step(self, r, Z, sigma, sinv):
        """One layer: sigma (X_r -> Z_r, a list) and sinv (its inverse) are
        extended in place to the next layer; False if there is no isomorphism."""
        if self.G[r] is None:
            out = self.step_ea(r, Z, sigma, sinv)
            if out is not _FALLBACK:
                return out
            # H of this layer is not elementary abelian: permutation groups from here
            self.solver.stats["luks_ea_fallback"] += 1
            assert len(self.L) == r + 1 and len(self.G) == r + 1
            self.L.pop()
            self.G[r] = PermGroup(self.X.start[r + 1], self.cur.tuples(self.X.start[r + 1]),
                                  order=self.cur.order())
        return self._step_perm(r, Z, sigma, sinv)

    # -- the elementary abelian path (no Schreier-Sims) ------------------------------
    def layer1_ea(self, r):
        """Phase-1 data of step r on the elementary abelian path: the same
        positions and string as layer1, and the action on the positions of the
        generators moving a point of an attachment set (the others fix every
        position)."""
        if len(self.L) > r:
            return self.L[r]
        X, st = self.X, self.solver.stats
        G, gens, who = self.cur, self.cur.gens, self.cur.who
        L = _LayerEA()
        L.r, L.Gpp = r, None
        L.b, L.c = X.start[r + 1], X.start[r + 2]
        att = X.attachments(r)
        L.A = list(att)
        L.aidx = {S: s for s, S in enumerate(L.A)}
        L.T = att
        L.slot = {}
        for s, S in enumerate(L.A):
            for k, t in enumerate(att[S]):
                L.slot[t] = (s, k)
        S_list = list(L.A)
        sidx = dict(L.aidx)
        for S in S_list:
            for gid in G.active_on(S):
                g = gens[gid]
                S2 = frozenset([g.get(i, i) for i in S])
                if S2 not in sidx:
                    sidx[S2] = len(S_list)
                    S_list.append(S2)
        L.S, L.sidx = S_list, sidx
        xS = [0] * len(S_list)
        for s, S in enumerate(L.A):
            xS[s] = self.code(tuple(X.col[t] for t in att[S]))
        L.xS = tuple(xS)
        act_ids = G.active_on(set().union(*S_list) if S_list else ())
        L.act_ids = act_ids
        L.act_dicts = [gens[g] for g in act_ids]
        acts = []
        for g in L.act_dicts:
            acts.append(tuple([sidx[frozenset([g.get(i, i) for i in S])] for S in S_list]))
        L.act1 = EAAction(len(act_ids), acts, len(S_list))
        st["luks_phase1_max_degree"] = max(st["luks_phase1_max_degree"], len(S_list))
        self.L.append(L)
        return L

    def layer2_ea(self, L, N):
        """Phase-2 data from G'' = the combinations N of the generators L.act_ids
        (plus every generator acting trivially on the positions). H =
        rho(G'') x| prod Sym(twin class & color) is elementary abelian iff
        every color block of a twin class has <= 2 members and G'' fixes each
        twin class holding a block of 2 (then H = G''+ x Z_2^t, g+ = (g, h_g) with
        h_g mapping the k-th member of T_S to the k-th of T_(S^g)). Returns
        False if not, without changing anything. Otherwise self.cur becomes H:
        the generators are extended in place to layer r + 1 and the twin swaps
        added."""
        X, st, G = self.X, self.solver.stats, self.cur
        b, c = L.b, L.c
        A, aidx, T, slot, col = L.A, L.aidx, L.T, L.slot, X.col
        nA = len(A)
        # the elements of the new basis that move some attachment set, and their
        # permutations of the sets; basis vectors with one bit keep the generator
        gpp = []
        for i, v in enumerate(N):
            if v & (v - 1) == 0:
                g = L.act_dicts[v.bit_length() - 1]
            else:
                ds, u = [], v
                while u:
                    b0 = u & -u
                    ds.append(L.act_dicts[b0.bit_length() - 1])
                    u ^= b0
                g = compose(ds)
            p = None
            for s, S in enumerate(A):
                q = None
                for t in S:
                    if t in g:
                        q = aidx[frozenset([g.get(j, j) for j in S])]
                        break
                if q is not None and q != s:
                    if p is None:
                        p = list(range(nA))
                    p[s] = q
            if p is not None:
                gpp.append((i, g, p))
        # the check; then the extension data, computed before anything changes
        swaps = []
        for s, S in enumerate(A):
            ts = T[S]
            i = 0
            while i < len(ts):
                j = i
                while j < len(ts) and col[ts[j]] == col[ts[i]]:
                    j += 1
                if j - i >= 3:
                    return False
                if j - i == 2:
                    if any(p[s] != s for _, _, p in gpp):
                        return False
                    swaps.append({ts[i]: ts[i + 1], ts[i + 1]: ts[i]})
                i = j
        ext = {}                        # basis index i -> new entries on layer r + 1
        for i, g, p in gpp:
            e = {}
            for s, S in enumerate(A):
                if p[s] != s:
                    img = T[A[p[s]]]
                    for k, t in enumerate(T[S]):
                        e[t] = img[k]
            ext[i] = e
        st["luks_twin_max"] = max([st["luks_twin_max"]] + [len(ts) for ts in T.values()])
        # commit: self.cur becomes H
        newids = G.restrict(L.act_ids, N)
        for i, e in ext.items():
            G.extend(newids[i], e)
        for sw in swaps:
            G.add(sw)
        L.Gpp = True
        st["luks_phase2_max_log2_order"] = max(st["luks_phase2_max_log2_order"], len(G))
        L.act2 = None
        L.h_ids = L.h_dicts = ()
        if not X.inner_edges(L.r):
            return True
        pairs, pidx = [], {}
        for t in range(b, c):
            for u in X.adj[t]:
                if t < u < c:
                    pidx[(t, u)] = len(pairs)
                    pairs.append((t, u))
        ne = len(pairs)
        gens = G.gens
        for p, q in pairs:
            for gid in G.active_on((p, q)):
                h = gens[gid]
                hp, hq = h.get(p, p), h.get(q, q)
                pq = (hp, hq) if hp < hq else (hq, hp)
                if pq not in pidx:
                    pidx[pq] = len(pairs)
                    pairs.append(pq)
        h_ids = G.active_on(set().union(*pairs))
        L.h_ids = h_ids
        L.h_dicts = [gens[g] for g in h_ids]
        act = []
        for h in L.h_dicts:
            img = []
            for p, q in pairs:
                hp, hq = h.get(p, p), h.get(q, q)
                img.append(pidx[(hp, hq) if hp < hq else (hq, hp)])
            act.append(tuple(img))
        L.pairs, L.act2 = pairs, EAAction(len(h_ids), act, len(pairs))
        L.x2 = tuple([1] * ne + [0] * (len(pairs) - ne))
        st["luks_phase2_max_degree"] = max(st["luks_phase2_max_degree"], len(pairs))
        return True

    def step_ea(self, r, Z, sigma, sinv):
        L = self.layer1_ea(r)
        b, c = L.b, L.c
        attZ = Z.attachments(r)
        yS = [0] * len(L.S)
        for SZ, ts in attZ.items():
            s = L.sidx.get(frozenset([sinv[j] for j in SZ]))
            if s is None:
                return False
            yS[s] = self.code(tuple([Z.col[t] for t in ts]))
        sol = L.act1.iso(L.xS, yS)
        if sol is None:
            return False
        a0, N = sol
        if L.Gpp is None:
            if not self.layer2_ea(L, N):
                return _FALLBACK
        if a0:
            self._apply_left(sigma, sinv, self._prod(L.act_dicts, a0), b)
        psi = [0] * (c - b)
        for Sx, ts in L.T.items():
            tz = attZ.get(frozenset([sigma[i] for i in Sx]))
            if tz is None or len(tz) != len(ts):
                raise AssertionError("phase 1 left twin classes unmatched")
            for t, u in zip(ts, tz):
                psi[t - b] = u
        if L.act2 is None:
            if Z.inner_edges(r):
                return False
            self._push_group(r, None)
            self._append(sigma, sinv, psi, b)
            return True
        y2 = [1 if psi[q - b] in Z.adj[psi[p - b]] else 0 for p, q in L.pairs]
        if sum(y2) != Z.inner_edges(r):
            return False
        sol = L.act2.iso(L.x2, y2)
        if sol is None:
            return False
        a2, N2 = sol
        self._push_group(r, N2)
        if a2:
            h = self._prod(L.h_dicts, a2)  # (g0 on X_r, h0 on layer r + 1)
            self._apply_left(sigma, sinv, h, b)
            psi = [psi[h.get(t, t) - b] for t in range(b, c)]
        self._append(sigma, sinv, psi, b)
        return True

    @staticmethod
    def _prod(dicts, a):
        """The product of the generators with bits in a."""
        ds = []
        while a:
            b = a & -a
            ds.append(dicts[b.bit_length() - 1])
            a ^= b
        return compose(ds)

    @staticmethod
    def _apply_left(sigma, sinv, g, b):
        """sigma[i] = old sigma[g[i]] for i < b (g on the old points only: g
        may also move later points, which sigma does not see yet)."""
        ups = [(p, sigma[q]) for p, q in g.items() if p < b]
        for p, v in ups:
            sigma[p] = v
            sinv[v] = p

    @staticmethod
    def _append(sigma, sinv, psi, b):
        c = b + len(psi)
        if len(sinv) < c:
            sinv.extend([0] * (c - len(sinv)))
        for t, u in zip(range(b, c), psi):
            sinv[u] = t
        sigma.extend(psi)

    def _push_group(self, r, N2):
        """G_{r+1}: self.cur restricted to Aut_H(x2) (the combinations N2 of
        the generators L.h_ids, or all of H when N2 is None), once per layer."""
        if len(self.G) != r + 1:
            return
        G = self.cur
        if N2 is not None:
            G.restrict(self.L[r].h_ids, N2)
        self.G.append(None)
        st = self.solver.stats
        st["luks_ea_layers"] += 1
        st["luks_group_max_log2_order"] = max(st["luks_group_max_log2_order"], len(G))

    def _step_perm(self, r, Z, sigma, sinv):
        X, S = self.X, self.solver
        L = self.layer1(r)
        b, c = L.b, L.c
        # (1) attachment sets of Z, pulled back to X's indices by sigma
        attZ = Z.attachments(r)
        yS = [0] * len(L.S)
        for SZ, ts in attZ.items():
            s = L.sidx.get(frozenset(sinv[j] for j in SZ))
            if s is None:               # x is 0 on the whole G_r-orbit closure
                return False
            yS[s] = self.code(tuple(Z.col[t] for t in ts))
        yS = tuple(yS)
        first = L.Gpp is None
        sig = sigma
        if L.P1 is None:
            if yS != L.xS:
                return False
            rep = None
            if first:
                L.Gpp = self.G[r]
        else:
            res = S.solve(L.P1, range(len(L.S)), L.xS, yS)
            if res is None:
                return False
            if first:
                phi = L.phi1
                L.Gpp = PermGroup(b, [phi.lift(h) for h in res.gens] + phi.kernel().gens,
                                  ambient_base=self.G[r].short_base())
            rep = L.phi1.lift(res.rep)
        if rep is not None:
            sig = list(mul(rep, sigma))
        if first:
            self.layer2(L)
        # (2) psi: X's twin classes onto Z's (by rank: colors agree after (1))
        psi = [0] * (c - b)
        for Sx, ts in L.T.items():
            tz = attZ.get(frozenset(sig[i] for i in Sx))
            if tz is None or len(tz) != len(ts):
                raise AssertionError("phase 1 left twin classes unmatched")
            for t, u in zip(ts, tz):
                psi[t - b] = u
        if L.H2 is None:
            if Z.inner_edges(r):
                return False
            h0, auts = None, L.gens2
        else:
            pairs, nV = L.pairs, c - b
            y2 = [0] * len(L.x2)
            ones = 0
            for j, (p, q) in enumerate(pairs):
                if psi[q] in Z.adj[psi[p]]:
                    y2[nV + j] = 1
                    ones += 1
            if ones != Z.inner_edges(r):  # an edge of Z outside the positions
                return False
            res = S.solve(L.H2, range(len(y2)), L.x2, tuple(y2))
            if res is None:
                return False
            h0, auts = res.rep, res.gens
        if len(self.G) == r + 1:
            G1 = PermGroup(c, [self.extend(L, h) for h in auts] + L.kernel_ext)
            st = S.stats
            st["luks_group_max_log2_order"] = max(st["luks_group_max_log2_order"],
                                                  round(math.log2(G1.order())))
            if self.ea and G1.order() == 1 << len(G1.gens) and is_ea2(G1.gens, c):
                self.cur = SparseEA.from_tuples(G1.gens)  # (G1.gens is irredundant: a basis)
                self.G.append(None)
            else:
                self.G.append(G1)
        if h0 is None:
            new = list(sig) + psi
        else:
            g0 = self.lift2(L, h0)
            new = list(mul(g0, sig)) + [psi[h0[t - b]] for t in range(b, c)]
        sigma[:] = new
        if len(sinv) < c:
            sinv.extend([0] * (c - len(sinv)))
        for i, v in enumerate(new):
            sinv[v] = i
        return True

    def lift2(self, L, h):
        """g in G'' inducing on the attachment sets of X what h (a permutation
        of layer r + 1, in the phase-2 group) induces."""
        if L.rho is None:
            return identity(L.b)
        b, T, A, slot = L.b, L.T, L.A, L.slot
        p = tuple(slot[b + h[T[S][0] - b]][0] for S in A)
        return L.rho.lift(p)

    def extend(self, L, h):
        """g+ for h in Aut_H2(x2): an element of G_{r+1}."""
        b = L.b
        return tuple(self.lift2(L, h)) + tuple(b + h[t] for t in range(L.c - b))

    def aut(self):
        """Generators of G_R = Aut_f(X) as index permutations (the chain must
        be complete)."""
        assert len(self.G) == self.steps() + 1
        G = self.G[-1]
        if G is None:
            return self.cur.tuples(self.X.start[-1])
        return list(G.gens)


# -- connected graphs -------------------------------------------------------------
def edge_invariants(g, edges):
    """For each oriented edge (u, v) in edges: the colors of u and v and the
    multiset of (d(u, w), d(v, w), color of w) over all vertices w (with
    more than 4 colors, of (d(u, w), d(v, w)) only: still an invariant,
    and far cheaper; the chains then test a few more roots). The
    distances come from bit-parallel balls (ball_{t+1}(v) = the union of
    ball_t over v and its neighbours, as int bitmasks), so the cost is
    about diameter * |E| big-int operations instead of n BFS runs."""
    n, nbr, col = g.n, g.nbr, g.col
    cur = [1 << v for v in range(n)]
    spheres = [cur]
    while True:
        nxt = []
        for v in range(n):
            b = cur[v]
            for w in nbr[v]:
                b |= cur[w]
            nxt.append(b)
        if nxt == cur:
            break
        spheres.append([b ^ a for a, b in zip(cur, nxt)])
        cur = nxt
    D = len(spheres)
    masks = {}
    for v in range(n):
        masks[col[v]] = masks.get(col[v], 0) | (1 << v)
    cmasks = sorted(masks.items())
    out = []
    for u, v in edges:
        items = []
        for i in range(D):
            su = spheres[i][u]
            for j in (i - 1, i, i + 1):
                if 0 <= j < D:
                    x = su & spheres[j][v]
                    if x:
                        if len(cmasks) == 1 or len(cmasks) > 4:
                            items.append((i, j, -1, x.bit_count()))
                        else:
                            for c, m in cmasks:
                                k = (x & m).bit_count()
                                if k:
                                    items.append((i, j, c, k))
        out.append((col[u], col[v], tuple(items)))
    return out


# -- the class of candidate root edges ----------------------------------------------
BFS_ENDS = 64                           # at most this many BFS runs per stage


def _bfs_dist(g, s):
    """Distances from s in the connected graph g (a list)."""
    n, nbr = g.n, g.nbr
    dist = [-1] * n
    dist[s] = 0
    cur = [s]
    d = 0
    while cur:
        d += 1
        nxt = []
        for v in cur:
            for w in nbr[v]:
                if dist[w] < 0:
                    dist[w] = d
                    nxt.append(w)
        cur = nxt
    return dist


def _nc(g):
    """Number of colors of g (1 or more than 4 colors: invariants ignore colors)."""
    return len(set(g.col))


def _profile_keys(g, ends, use_col):
    """{v: the profile of v} for v in ends: (color of v, sphere sizes around v, by color
    if use_col). By BFS when there are at most BFS_ENDS ends, else by
    bit-parallel balls (cur[v] = ball of radius t around v, as int bitmasks).
    The two forms are not equal, but the choice depends only on len(ends)."""
    col = g.col
    if len(ends) <= BFS_ENDS:
        out = {}
        for v in ends:
            d = _bfs_dist(g, v)
            if use_col:
                out[v] = (col[v], tuple(sorted(Counter(zip(d, col)).items())))
            else:
                out[v] = (col[v], tuple(sorted(Counter(d).items())))
        return out
    spheres = _spheres(g)
    if use_col:
        masks = {}
        for v in range(g.n):
            masks[col[v]] = masks.get(col[v], 0) | (1 << v)
        cm = [m for _, m in sorted(masks.items())]
        return {v: (col[v], tuple(tuple((s[v] & m).bit_count() for m in cm) for s in spheres))
                for v in ends}
    return {v: (col[v], tuple(s[v].bit_count() for s in spheres)) for v in ends}


def _spheres(g):
    """[S_0, S_1, ..., S_D]: S_t[v] is the bitmask of the vertices at distance
    exactly t from v (bit-parallel balls)."""
    n, nbr = g.n, g.nbr
    cur = [1 << v for v in range(n)]
    spheres = [cur]
    while True:
        nxt = []
        for v in range(n):
            b = cur[v]
            for w in nbr[v]:
                b |= cur[w]
            nxt.append(b)
        if nxt == cur:
            return spheres
        spheres.append([b ^ a for a, b in zip(cur, nxt)])
        cur = nxt


STAGE1_SMALL = 8                         # stop refining stage 1 at a class of this size


def _truncated_profiles(g, edges, C, use_col):
    """Stage-1 keys of the edges C by sphere sizes, radius by radius, stopped
    as soon as the smallest class of the edges of C has at most STAGE1_SMALL
    members (or the balls have stopped growing): the profile up to radius t
    (with t determined by the profiles themselves) is an isomorphism
    invariant, and the radius needed is usually far below the diameter
    (Miyazaki graphs: diameter ~ n/3). Each round costs one bit-parallel
    ball step over all vertices. The ranks are canonical (sorted values)."""
    n, nbr, col = g.n, g.nbr, g.col
    if use_col:
        masks = {}
        for v in range(n):
            masks[col[v]] = masks.get(col[v], 0) | (1 << v)
        cm = [m for _, m in sorted(masks.items())]
    cur = [1 << v for v in range(n)]
    key = list(col)
    k1 = [(key[edges[f][0]], key[edges[f][1]]) for f in C]
    while min(Counter(k1).values()) > STAGE1_SMALL:
        nxt = []
        for v in range(n):
            b = cur[v]
            for w in nbr[v]:
                b |= cur[w]
            nxt.append(b)
        if nxt == cur:
            break
        if use_col:
            counts = [tuple(((b ^ a) & m).bit_count() for m in cm) for a, b in zip(cur, nxt)]
        else:
            counts = [(b ^ a).bit_count() for a, b in zip(cur, nxt)]
        cur = nxt
        sig = list(zip(key, counts))
        rank = {x: i for i, x in enumerate(sorted(set(sig)))}
        key = [rank[x] for x in sig]
        k1 = [(key[edges[f][0]], key[edges[f][1]]) for f in C]
    return k1


def _inv_bfs(g, edges, use_col):
    """Edge invariants of the oriented edges (u, v) (the color pair and the
    multiset of (d(u, w), d(v, w), color of w if use_col) over all w) by BFS.
    Equal in content to edge_invariants (in another form, and only used in place
    of it when the number of edges is at most BFS_ENDS)."""
    col = g.col
    cache = {}

    def dist(s):
        d = cache.get(s)
        if d is None:
            d = cache[s] = _bfs_dist(g, s)
        return d

    out = []
    for u, v in edges:
        du, dv = dist(u), dist(v)
        if use_col:
            c = Counter(zip(du, dv, col))
        else:
            c = Counter(zip(du, dv))
        out.append((col[u], col[v], tuple(sorted(c.items()))))
    return out


def root_class(g, edges, keys=None, stats=None):
    """A class of oriented edges (indices into edges) that every isomorphism
    respects, chosen in stages, each stage narrowing the previous one to its
    class minimizing (size, key):

      0. the pair of 1-WL colors of the ends (g.col must be canonical: colors
         that a graph isomorphism preserves);
      1. the pair of sphere-size profiles of the ends;
      2. the edge invariants of gi.bounded (end colors and the multiset of
         (d(u, w), d(v, w), color of w)); skipped when the class is so large
         that it would cost more than trying more roots (rule below).

    keys is None: choose the classes and return (C, keys), with keys the
    (key, class size) per stage. keys given: select the classes of the
    same keys instead (for the other graph); returns None if a class does
    not have the same size. The stage rules depend only on the class sizes
    and on n, so two isomorphic graphs go through the same stages."""
    n, col = g.n, g.col
    ncol = _nc(g)
    use_col = 1 < ncol <= 4
    k0 = [(col[u], col[v]) for u, v in edges]
    cnt = Counter(k0)
    if keys is None:
        best = min(cnt, key=lambda k: (cnt[k], k))
    else:
        best = keys[0][0]
    C = [f for f, k in enumerate(k0) if k == best]
    out = [(best, len(C))]
    if keys is not None and len(C) != keys[0][1]:
        return None
    if stats is not None:
        stats["luks_root_stage0"] = max(stats["luks_root_stage0"], len(C))
    if len(C) <= 1:
        return C, out
    ends = sorted(set(v for f in C for v in edges[f]))
    if len(ends) <= BFS_ENDS:
        prof = _profile_keys(g, ends, use_col)
        k1 = [(prof[edges[f][0]], prof[edges[f][1]]) for f in C]
    else:
        k1 = _truncated_profiles(g, edges, C, use_col)
    cnt = Counter(k1)
    if keys is None:
        best = min(cnt, key=lambda k: (cnt[k], k))
    else:
        best = keys[1][0]
    C2 = [f for f, k in zip(C, k1) if k == best]
    out.append((best, len(C2)))
    if keys is not None and (len(keys) < 2 or len(C2) != keys[1][1]):
        return None
    C = C2
    if stats is not None:
        stats["luks_root_stage1"] = max(stats["luks_root_stage1"], len(C))
    if len(C) <= 1:
        return C, out
    # stage 2 only when it is cheap compared with trying the edges as roots: the
    # bit-parallel invariant costs about len(C) * diameter big-int operations
    if len(C) > BFS_ENDS:
        spheres_cost = len(C) * n
        if spheres_cost > ROOT_STAGE2_BUDGET * n * n:
            return C, out
    pairs = [edges[f] for f in C]
    k2 = _inv_bfs(g, pairs, use_col) if len(C) <= BFS_ENDS else edge_invariants(g, pairs)
    cnt = Counter(k2)
    if keys is None:
        best = min(cnt, key=lambda k: (cnt[k], k))
    else:
        if len(keys) < 3:
            return None
        best = keys[2][0]
    C2 = [f for f, k in zip(C, k2) if k == best]
    out.append((best, len(C2)))
    if keys is not None and len(C2) != keys[2][1]:
        return None
    if stats is not None:
        stats["luks_root_stage2"] = max(stats["luks_root_stage2"], len(C2))
    return C2, out


ROOT_STAGE2_BUDGET = 2                  # see root_class


class _Connected:
    """A connected graph with the class of root edges (root_class) or, with
    root="degree", the invariants of all oriented edges; with aut=True also
    Aut(X), the orbits of Aut(X) on the root class and the chains used."""

    def __init__(self, g, solver, aut=True, root="class", stable=False, rooted_wl=True, ea=True,
                 layers="class", max_tests=None):
        self.g, self.solver, self.root, self.ea, self.stable = g, solver, root, ea, stable
        self.max_tests = max_tests
        self.layers = layers if rooted_wl else "bfs"
        self.rooted_wl = rooted_wl
        n = g.n
        self.edges = [(u, v) for u in range(n) for v in g.nbr[u]]
        self.eidx = {e: i for i, e in enumerate(self.edges)}
        self.invs = None
        self.cls = None
        self.keys = None
        self.chains = {}
        self.gens = None
        self.cert0 = None
        self.cert_hash = {}
        if aut and self.edges:
            self.compute_aut()

    def invariants(self):
        if self.invs is None:
            self.invs = edge_invariants(self.g, self.edges)
        return self.invs

    def rooted(self, f):
        u0, u1 = self.edges[f]
        col = rooted_colors(self.g, u0, u1, self.stable) if self.rooted_wl else self.g.col
        return _Seed(self.g, u0, u1, col)

    def cert(self, f, seed=None):
        """(cert, hash): a certificate of the rooted graph (g, edges[f]) when its
        rooted 1-WL coloring is discrete, else (None, 0). Two rooted graphs
        with discrete colorings are isomorphic iff their certificates are equal
        (the color names are a function of the rooted isomorphism type, and
        the certificate lists the root colors, the g.col of each color and the
        edges in color names). seed: the rooted graph if already computed."""
        if seed is None:
            seed = self.rooted(f)
        return discrete_cert(self.g, seed)

    def chain(self, f, seed=None):
        c = self.chains.get(f)
        if c is None:
            sd = self.rooted(f) if seed is None else seed
            plan = class_plan(sd.g, sd.col, sd.u0, sd.u1) if self.layers == "class" else None
            c = self.chains[f] = _Chain(_Rooted(sd.g, sd.u0, sd.u1, sd.col, plan), self.solver,
                                        self.ea, plan)
            self.solver.stats["luks_layers_max"] = max(self.solver.stats["luks_layers_max"],
                                                       c.steps())
        return c

    def vertex_map(self, X, Z, sigma):
        out = [0] * len(sigma)
        for i, s in enumerate(sigma):
            out[X.order[i]] = Z.order[s]
        return tuple(out)

    def _class(self):
        """The class of oriented edges the root is taken from: root_class,
        or with root="degree" the invariant class of an edge of maximum degree
        sum. Returns (f0, the class as a list of edge indices)."""
        if self.root == "degree":
            invs = self.invariants()
            cls = Counter(invs)
            deg = [len(x) for x in self.g.nbr]
            f0 = min(range(len(self.edges)), key=lambda i: (
                -deg[self.edges[i][0]] - deg[self.edges[i][1]], cls[invs[i]], i))
            return f0, [f for f in range(len(self.edges)) if invs[f] == invs[f0]]
        self.cls, self.keys = root_class(self.g, self.edges, stats=self.solver.stats)
        return self.cls[0], self.cls

    def compute_aut(self):
        f0, C = self._class()
        self.f0 = f0
        self.cls = C
        seed0 = self.rooted(f0)
        ch = self.chain(f0, seed0)
        X = ch.X
        if ch.run(X) is None:           # (X, f0) -> (X, f0) always exists
            raise AssertionError("no automorphism found for the root")
        gens = [self.vertex_map(X, X, g) for g in ch.aut()]
        cert0, h0, by0 = discrete_cert(self.g, seed0)
        self.cert_hash = {f0: h0} if cert0 is not None else {}
        self.cert0 = cert0
        pos = {f: i for i, f in enumerate(C)}
        parent = list(range(len(C)))

        def find(v):
            while parent[v] != v:
                parent[v] = parent[parent[v]]
                v = parent[v]
            return v

        comps = [len(C)]                # number of orbits on C of the group found so far

        def absorb(g):
            if comps[0] == 1:           # (one orbit: more generators change nothing)
                return
            for i, f in enumerate(C):   # (Aut(X) maps the class onto itself)
                u, v = self.edges[f]
                a, b = find(i), find(pos[self.eidx[(g[u], g[v])]])
                if a != b:
                    parent[max(a, b)] = min(a, b)
                    comps[0] -= 1

        for g in gens:
            absorb(g)
        failed = []
        i0 = pos[f0]
        for f in C:
            if f == f0:
                continue
            rf = find(pos[f])
            if rf == find(i0) or any(find(pos[e]) == rf for e in failed):
                continue
            self.solver.stats["luks_aut_tests"] += 1
            self._budget()
            seed = self.rooted(f)
            if cert0 is not None:       # rooted colorings discrete: no chain needed
                self.solver.stats["luks_cert_tests"] += 1
                cf, hf, byf = discrete_cert(self.g, seed)
                if cf is None or hf != h0 or cf != cert0:
                    self.cert_hash[f] = hf if cf is not None else None
                    failed.append(f)
                    continue
                self.cert_hash[f] = hf
                g = [0] * len(by0)
                for c, v in enumerate(by0):
                    g[v] = byf[c]
                g = tuple(g)
                gens.append(g)
                absorb(g)
                continue
            Z = ch.target(seed)
            s = ch.run(Z)
            if s is None:
                failed.append(f)
                continue
            g = self.vertex_map(X, Z, s)
            gens.append(g)
            absorb(g)
        self.gens = gens
        self.find = lambda f: find(pos[f])

    def _budget(self):
        """max_tests rooted tests in all (a test costs a refinement of the
        graph at least); see gi/graph.py (dispatch)."""
        st = self.solver.stats
        if self.max_tests is not None and st["luks_aut_tests"] + st["luks_iso_tests"] > self.max_tests:
            raise OverBudget

    def iso(self, other):
        """A vertex map self -> other (connected, same color names), or None."""
        if self.g.n != other.g.n or len(self.edges) != len(other.edges):
            return None
        if self.root == "degree":
            if Counter(self.invariants()) != Counter(other.invariants()):
                return None
            inv0 = self.invs[self.f0]
            e1 = next((i for i, v in enumerate(other.invs) if v == inv0), None)
            if e1 is None:
                return None
        else:
            res = root_class(other.g, other.edges, self.keys)
            if res is None:
                return None
            e1 = res[0][0]
        seed = other.rooted(e1)
        cy, hy, by = discrete_cert(other.g, seed)
        reps, seen = [self.f0], {self.find(self.f0)}
        for f in self.cls:
            if self.find(f) not in seen:
                seen.add(self.find(f))
                reps.append(f)
        hx = getattr(self, "cert_hash", {})
        for f in reps:
            self.solver.stats["luks_iso_tests"] += 1
            self._budget()
            h = hx.get(f)
            if h is not None and cy is not None and h != hy:
                self.solver.stats["luks_cert_tests"] += 1
                continue                # both discrete, the certificates differ
            cx, hxf, bx = discrete_cert(self.g, self.rooted(f))
            if cx is not None or cy is not None:
                self.solver.stats["luks_cert_tests"] += 1
                if cx is None or cy is None or cx != cy:
                    continue            # (one is discrete and the other not, or the
                g = [0] * len(bx)       # certificates differ: no rooted isomorphism)
                for c, v in enumerate(bx):
                    g[v] = by[c]
                return tuple(g)
            ch = self.chain(f)
            Z = ch.target(seed)
            s = ch.run(Z)
            if s is not None:
                return self.vertex_map(ch.X, Z, s)
        return None


def discrete_cert(g, seed):
    """See _Connected.cert: (certificate, its hash) or (None, 0) if the rooted
    coloring is not discrete. Also the vertex map color -> vertex is returned as
    the third entry (cert, h, by), by[c] = the vertex of color c."""
    col = seed.col
    n = g.n
    by = [None] * n
    for v, c in enumerate(col):
        if c >= n or by[c] is not None:
            return None, 0, None
        by[c] = v
    nbr, gc = g.nbr, g.col
    rows = tuple(tuple(sorted([col[w] for w in nbr[by[i]]])) for i in range(n))
    cert = (col[seed.u0], col[seed.u1], tuple(gc[by[i]] for i in range(n)), rows)
    return cert, hash(cert), by


def _invert(p):
    r = [0] * len(p)
    for i, j in enumerate(p):
        r[j] = i
    return r


def bounded_iso(X, Y, solver=None, vcolors_x=None, vcolors_y=None, refine=True, root="class",
                rooted_wl=True, ea=True, layers="class"):
    """X, Y: adjacency matrices of undirected loopless graphs (any degree; the
    groups have composition factors in Sym(d - 1) for maximum degree d).
    Returns None if not isomorphic, else (sigma, aut_gens): sigma[i] is the
    image of vertex i (an isomorphism X -> Y) and aut_gens generate Aut(X)
    (vertex colors respected). solver: a Solver (default
    Solver(cameron_no_enum=True)); its stats count the reduction's work
    (luks_*). root: how the root edge f0 of each component is chosen,
    "class" (smallest invariant class, the fewest tests) or "degree" (an edge
    of maximum degree sum, which makes large twin classes appear early); it
    only changes the running time and which generators are returned.
    rooted_wl: each rooted graph gets the 1-WL colors with its root edge
    individualized (rooted_colors; exact, and it splits twin classes that
    plain layering keeps together, e.g. on multipedes). ea: while G_r is
    elementary abelian (and the layer's phase-2 group too), the layer is
    solved by linear algebra over F_2 (gi/ea2.py) instead of Solver.solve;
    exact either way. layers: "class" (with rooted_wl) layers each rooted
    graph by color classes in the order of class_plan, "bfs" by distance
    from the root edge (Luks's original order)."""
    if len(Y) != len(X):
        return None
    return bounded_iso_lists(_neighbours(X), _neighbours(Y), solver, vcolors_x, vcolors_y,
                             refine, root, rooted_wl, ea, layers)


def _check_lists(nbr):
    n = len(nbr)
    sets = [set(r) for r in nbr]
    for i, r in enumerate(nbr):
        if len(sets[i]) != len(r) or any(not 0 <= j < n for j in r):
            raise NotSimple("neighbour lists must hold distinct vertices")
        if i in sets[i]:
            raise NotSimple("loops are not supported")
        if any(i not in sets[j] for j in r):
            raise NotSimple("directed graphs are not supported")
    return [sorted(r) for r in nbr]


def bounded_iso_lists(nx, ny, solver=None, vcolors_x=None, vcolors_y=None, refine=True,
                      root="class", rooted_wl=True, ea=True, layers="class", max_tests=None):
    """bounded_iso for graphs given by neighbour lists (nx[v]: the neighbours
    of v; symmetric, no loops or repeats), without O(n^2) matrices. Same
    arguments and return value as bounded_iso."""
    n = len(nx)
    if len(ny) != n:
        return None
    if n == 0:
        return (), []
    solver = solver or Solver(cameron_no_enum=True)
    nx, ny = _check_lists(nx), _check_lists(ny)
    cx, cy = _joint_names(vcolors_x or [0] * n, vcolors_y or [0] * n)
    if refine:
        r = refine_1wl(nx, ny, cx, cy)
        if r is None:
            solver.stats["luks_refine_reject"] += 1
            return None
        cx, cy = r
    elif Counter(cx) != Counter(cy):
        return None
    if sorted(map(len, nx)) != sorted(map(len, ny)):
        return None
    gx, gy = _Graph(nx, cx), _Graph(ny, cy)
    px, py = _components(nx), _components(ny)
    if len(px) != len(py):
        return None

    def key(g, part):
        return (len(part), sum(len(g.nbr[v]) for v in part), tuple(sorted(g.col[v] for v in part)))

    # isomorphism classes of X's components: [rep, [(part, iso rep -> part)], key]
    classes = []
    for part in px:
        k = key(gx, part)
        sub = _induced(gx, part)
        for C in classes:
            if C[2] == k:
                t = _component_iso(C[0], sub, solver)
                if t is not None:
                    C[1].append((part, t))
                    break
        else:
            rep = (_Connected(sub, solver, root=root, stable=refine, rooted_wl=rooted_wl, ea=ea,
                              layers=layers, max_tests=max_tests)
                   if len(part) > 1 else _Single(sub))
            classes.append([rep, [(part, tuple(range(len(part))))], k])
    matches = [[] for _ in classes]
    for part in py:
        k = key(gy, part)
        sub = _induced(gy, part)
        for ci, C in enumerate(classes):
            if C[2] == k and len(matches[ci]) < len(C[1]):
                t = _component_iso(C[0], sub, solver)
                if t is not None:
                    matches[ci].append((part, t))
                    break
        else:
            return None
    sigma = [0] * n
    gens = []
    for C, M in zip(classes, matches):
        if len(M) != len(C[1]):
            return None
        rep, members = C[0], C[1]
        p1 = members[0][0]
        for g in rep.gens:              # Aut of the representative component
            h = list(range(n))
            for i, v in enumerate(p1):
                h[v] = p1[g[i]]
            gens.append(tuple(h))
        for (part, t), (ypart, s) in zip(members, M):
            ti = _invert(t)
            for i, v in enumerate(part):        # part -> rep -> ypart
                sigma[v] = ypart[s[ti[i]]]
        for part, t in members[1:]:     # swaps of the representative with each copy
            h = list(range(n))
            for i, v in enumerate(p1):
                h[v] = part[t[i]]
                h[part[t[i]]] = v
            gens.append(tuple(h))
    idn = identity(n)
    return tuple(sigma), [g for g in dict.fromkeys(gens) if g != idn]


class _Single:
    """A one-vertex component."""
    gens = ()

    def __init__(self, g):
        self.g = g


def _component_iso(rep, sub, solver):
    """A vertex map rep -> sub (connected graphs of equal size, edge count and
    color multiset), or None."""
    if isinstance(rep, _Single):
        return (0,) if rep.g.col == sub.col else None
    return rep.iso(_Connected(sub, solver, aut=False, stable=rep.stable, rooted_wl=rep.rooted_wl,
                              ea=rep.ea, layers=rep.layers, max_tests=rep.max_tests))
