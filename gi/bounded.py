class NotSimple(ValueError):
    pass


# -- graphs -------------------------------------------------------------------
class _Graph:
    """A vertex-colored simple graph: nbr[v] sorted neighbour lists."""
    __slots__ = ("n", "nbr", "col")

    def __init__(self, nbr, col):
        self.n, self.nbr, self.col = len(nbr), nbr, col


def _neighbours(A):
    n = len(A)
    nbr = []
    for i in range(n):
        if A[i][i]:
            raise NotSimple("loops are not supported")
        row = []
        for j in range(n):
            if A[i][j]:
                if not A[j][i]:
                    raise NotSimple("directed graphs are not supported")
                row.append(j)
        nbr.append(row)
    return nbr


def _joint_names(cx, cy):
    vals = set(cx) | set(cy)
    try:
        srt = sorted(vals)
    except TypeError:
        srt = sorted(vals, key=repr)
    rank = {v: i for i, v in enumerate(srt)}
    return [rank[c] for c in cx], [rank[c] for c in cy]


def refine_1wl(nx, ny, cx, cy):
    """Joint color refinement of two graphs (neighbour lists nx, ny, int
    colors cx, cy). New colors are ranks of (old color, sorted neighbour
    colors) in the union of both graphs' signatures, so every isomorphism
    maps the refined x-colors onto the refined y-colors. None if the color
    histograms differ."""
    k = len(set(cx) | set(cy))
    while True:
        if Counter(cx) != Counter(cy):
            return None
        sx = [(cx[v], tuple(sorted(cx[w] for w in nx[v]))) for v in range(len(nx))]
        sy = [(cy[v], tuple(sorted(cy[w] for w in ny[v]))) for v in range(len(ny))]
        cx, cy = _joint_names(sx, sy)
        k2 = len(set(cx) | set(cy))
        if k2 == k:
            return (cx, cy) if Counter(cx) == Counter(cy) else None
        k = k2


def _components(nbr):
    n = len(nbr)
    comp = [-1] * n
    out = []
    for s in range(n):
        if comp[s] >= 0:
            continue
        comp[s] = len(out)
        part = [s]
        for v in part:
            for w in nbr[v]:
                if comp[w] < 0:
                    comp[w] = comp[s]
                    part.append(w)
        out.append(sorted(part))
    return out


def _induced(g, part):
    loc = {v: i for i, v in enumerate(part)}
    return _Graph([[loc[w] for w in g.nbr[v]] for v in part], [g.col[v] for v in part])


# -- the layered structure from an oriented edge ---------------------------------
class _Rooted:
    """BFS layers of a connected graph from the oriented edge (u0, u1).
    Vertices are renumbered by layers: order[i] is the vertex of index i,
    start[r] the first index of layer r (start[-1] = n). down[i] lists the
    indices of the neighbours of index i in the next layer, adj[i] all
    neighbour indices, col[i] the color."""
    __slots__ = ("order", "start", "down", "adj", "col")

    def __init__(self, g, u0, u1):
        n = g.n
        dist = [-1] * n
        dist[u0] = dist[u1] = 0
        order = [u0, u1]
        start = [0, 2]
        cur = order[:]
        while True:
            nxt = []
            for v in cur:
                for w in g.nbr[v]:
                    if dist[w] < 0:
                        dist[w] = dist[v] + 1
                        nxt.append(w)
            if not nxt:
                break
            order.extend(nxt)
            start.append(len(order))
            cur = nxt
        if len(order) != n:
            raise ValueError("graph is not connected")
        pos = [0] * n
        for i, v in enumerate(order):
            pos[v] = i
        self.order, self.start = order, start
        self.adj = [frozenset(pos[w] for w in g.nbr[v]) for v in order]
        self.col = [g.col[v] for v in order]
        self.down = [sorted(pos[w] for w in g.nbr[v] if dist[w] == dist[v] + 1) for v in order]


class _Hat:
    """The data of step (b) for one layer of a chain (X side only)."""
    __slots__ = ("E", "lower", "upper", "eid", "lplus", "lpos", "first", "ups",
                 "pidx", "pairs", "group", "M", "x2", "tau", "kernel_ext", "b", "c")


class _Chain:
    """The groups G_r = Aut_f(X_r) of one rooted graph X (built lazily, as far
    as some target got) and the isomorphism cosets towards targets."""

    def __init__(self, X, solver):
        self.X, self.solver = X, solver
        self.G = [PermGroup(2)]         # G[r] = G_r on range(start[r + 1])
        self.Gp = []                    # Gp[r] = G' of step r (after (a))
        self.hat = []                   # hat[r] = _Hat of step r

    def steps(self):
        return len(self.X.start) - 2

    def run(self, Z):
        """sigma (index map X -> Z, an isomorphism of the rooted graphs) or
        None. Every step is exact, so None means no isomorphism maps the root
        of X to the root of Z."""
        X = self.X
        st = self.solver.stats
        st["luks_runs"] += 1
        if Z.start != X.start or Z.col[0] != X.col[0] or Z.col[1] != X.col[1]:
            return None
        sigma = (0, 1)
        for r in range(self.steps()):
            st["luks_steps"] += 1
            sigma = self.step(r, Z, sigma)
            if sigma is None:
                return None
        return sigma

    def step(self, r, Z, sigma):
        X, S = self.X, self.solver
        a, b = X.start[r], X.start[r + 1]
        G = self.G[r]
        # (a) down-degrees
        xd = tuple([-1] * a + [len(X.down[i]) for i in range(a, b)])
        yd = tuple([-1] * a + [len(Z.down[sigma[i]]) for i in range(a, b)])
        res = S.solve(G, range(a, b), xd, yd)
        if res is None:
            return None
        if len(self.Gp) == r:
            if list(res.gens) == list(G.gens):
                Gp = G
            else:
                Gp = PermGroup(b, res.gens, ambient_base=G.short_base())
            self.Gp.append(Gp)
        sigma = mul(res.rep, sigma)
        # (b) down-edges
        if len(self.hat) == r:
            self.hat.append(self.build_hat(r))
        H = self.hat[r]
        yz = self.ycodes(H, Z, sigma)
        if yz is None:
            S.stats["luks_outside"] += 1
            return None
        y2, upY = yz
        res = S.solve(H.group, range(H.M), H.x2, y2)
        if res is None:
            return None
        if len(self.G) == r + 1:
            gens = [self.extend(H, h) for h in res.gens] + H.kernel_ext
            self.G.append(PermGroup(H.c, gens))
        # the new isomorphism
        h0 = res.rep
        g0 = H.tau.lift(self.lower_map(H, h0))
        new = list(mul(g0, sigma))
        for es in H.ups:
            new.append(upY[h0[es[0]]])
        return tuple(new)

    def build_hat(self, r):
        X, S = self.X, self.solver
        st = S.stats
        Gp = self.Gp[r]
        a, b, c = X.start[r], X.start[r + 1], X.start[r + 2]
        H = _Hat()
        H.b, H.c = b, c
        H.lplus = [i for i in range(a, b) if X.down[i]]
        H.lpos = {v: t for t, v in enumerate(H.lplus)}
        E, eid = [], {}
        for i in H.lplus:
            for k in range(len(X.down[i])):
                eid[(i, k)] = len(E)
                E.append((i, k))
        nE = len(E)
        H.E, H.eid = E, eid
        H.lower = [i for i, _ in E]
        H.upper = [X.down[i][k] for i, k in E]
        H.first = [eid[(i, 0)] for i in H.lplus]
        ups = [[] for _ in range(b, c)]
        for e, t in enumerate(H.upper):
            ups[t - b].append(e)
        H.ups = ups
        # generators of H on E
        idE = identity(nE)
        gensE = []
        for g in Gp.gens:
            h = tuple(eid[(g[i], k)] for i, k in E)
            if h != idE:
                gensE.append(h)
        dmax = 0
        for i in H.lplus:
            dl = len(X.down[i])
            dmax = max(dmax, dl)
            if dl >= 2:
                gensE.extend(sym_gens(nE, [eid[(i, k)] for k in range(dl)]))
        H.tau = RestrictionHom(Gp, H.lplus)
        order = H.tau.image_order() * math.prod(math.factorial(len(X.down[i])) for i in H.lplus)
        # the pairs that are nonzero for X, and their H-orbits
        info = {}
        for es in ups:
            for p, q in combinations(es, 2):
                info[(p, q)] = 1
        for t in range(b, c):
            for t2 in X.adj[t]:
                if t < t2 < c:
                    for p in ups[t - b]:
                        for q in ups[t2 - b]:
                            info[(p, q) if p < q else (q, p)] = 2
        pairs = list(info)
        pidx = {pq: nE + j for j, pq in enumerate(pairs)}
        for p, q in pairs:              # (the list grows: a BFS over the orbits)
            for h in gensE:
                hp, hq = h[p], h[q]
                pq = (hp, hq) if hp < hq else (hq, hp)
                if pq not in pidx:
                    pidx[pq] = nE + len(pairs)
                    pairs.append(pq)
        H.pairs, H.pidx = pairs, pidx
        H.M = nE + len(pairs)
        gensD = []
        for h in gensE:
            img = list(h)
            for p, q in pairs:
                hp, hq = h[p], h[q]
                img.append(pidx[(hp, hq) if hp < hq else (hq, hp)])
            gensD.append(tuple(img))
        H.group = PermGroup(H.M, gensD, order=order)
        H.x2 = tuple([3 + X.col[t] for t in H.upper] + [info.get(pq, 0) for pq in pairs])
        H.kernel_ext = [tuple(k) + tuple(range(b, c)) for k in H.tau.kernel().gens]
        st["luks_hat_max_degree"] = max(st["luks_hat_max_degree"], H.M)
        st["luks_hat_max_log2_order"] = max(st["luks_hat_max_log2_order"],
                                            round(math.log2(order)) if order > 1 else 0)
        st["luks_delta_max"] = max(st["luks_delta_max"], dmax)
        return H

    def ycodes(self, H, Z, sigma):
        """The string of the target on H's positions (and the upper ends of
        the target's down-edges), or None when a pair that is nonzero for
        the target lies outside the positions (then no element of H maps
        x onto it: x is 0 on every pair outside them)."""
        b = H.b
        upY = [Z.down[sigma[i]][k] for i, k in H.E]
        nE = len(upY)
        ups = {}
        for e, t in enumerate(upY):
            ups.setdefault(t, []).append(e)
        vals = {}
        pidx = H.pidx
        for es in ups.values():
            for p, q in combinations(es, 2):
                j = pidx.get((p, q) if p < q else (q, p))
                if j is None:
                    return None
                vals[j] = 1
        c = H.c
        for t, es in ups.items():
            for t2 in Z.adj[t]:
                if t < t2 < c and t2 >= b:
                    for p in es:
                        for q in ups[t2]:
                            j = pidx.get((p, q) if p < q else (q, p))
                            if j is None:
                                return None
                            vals[j] = 2
        y2 = [3 + Z.col[t] for t in upY] + [0] * (H.M - nE)
        for j, v in vals.items():
            y2[j] = v
        return tuple(y2), upY

    def lower_map(self, H, h):
        """The permutation of the lower ends (in tau's numbering) induced by
        h in H."""
        lower, lpos = H.lower, H.lpos
        return tuple(lpos[lower[h[e]]] for e in H.first)

    def extend(self, H, h):
        """g+ for h in Aut_H(x): an element of G_{r+1} (see the module
        docstring)."""
        g = H.tau.lift(self.lower_map(H, h))
        return tuple(g) + tuple(H.upper[h[es[0]]] for es in H.ups)

    def aut(self):
        """Generators of G_R = Aut_f(X) as index permutations (the chain must
        be complete)."""
        assert len(self.G) == self.steps() + 1
        return list(self.G[-1].gens)


# -- connected graphs -------------------------------------------------------------
class _Connected:
    """A connected graph with its oriented-edge invariants; with aut=True also
    Aut(X), the orbits of Aut(X) on oriented edges and the chains used."""

    def __init__(self, g, solver, aut=True):
        self.g, self.solver = g, solver
        n = g.n
        self.edges = [(u, v) for u in range(n) for v in g.nbr[u]]
        self.eidx = {e: i for i, e in enumerate(self.edges)}
        self.invs = self.invariants()
        self.chains = {}
        self.gens = None
        if aut and self.edges:
            self.compute_aut()

    def invariants(self):
        g = self.g
        n = g.n
        dist = []
        for s in range(n):
            d = [-1] * n
            d[s] = 0
            q = [s]
            for v in q:
                for w in g.nbr[v]:
                    if d[w] < 0:
                        d[w] = d[v] + 1
                        q.append(w)
            dist.append(d)
        K = n + 1
        C = 1 + max(g.col, default=0)
        out = []
        for u, v in self.edges:
            du, dv = dist[u], dist[v]
            cnt = Counter((du[w] * K + dv[w]) * C + g.col[w] for w in range(n))
            out.append((g.col[u], g.col[v], tuple(sorted(cnt.items()))))
        return out

    def rooted(self, f):
        return _Rooted(self.g, *self.edges[f])

    def chain(self, f):
        c = self.chains.get(f)
        if c is None:
            c = self.chains[f] = _Chain(self.rooted(f), self.solver)
        return c

    def vertex_map(self, X, Z, sigma):
        out = [0] * len(sigma)
        for i, s in enumerate(sigma):
            out[X.order[i]] = Z.order[s]
        return tuple(out)

    def compute_aut(self):
        cls = Counter(self.invs)
        f0 = min(range(len(self.edges)), key=lambda i: (cls[self.invs[i]], i))
        self.f0 = f0
        ch = self.chain(f0)
        X = ch.X
        if ch.run(X) is None:           # (X, f0) -> (X, f0) always exists
            raise AssertionError("no automorphism found for the root")
        gens = [self.vertex_map(X, X, g) for g in ch.aut()]
        parent = list(range(len(self.edges)))

        def find(v):
            while parent[v] != v:
                parent[v] = parent[parent[v]]
                v = parent[v]
            return v

        def absorb(g):
            for i, (u, v) in enumerate(self.edges):
                a, b = find(i), find(self.eidx[(g[u], g[v])])
                if a != b:
                    parent[max(a, b)] = min(a, b)

        for g in gens:
            absorb(g)
        failed = []
        inv0 = self.invs[f0]
        for f in range(len(self.edges)):
            if f == f0 or self.invs[f] != inv0:
                continue
            rf = find(f)
            if rf == find(f0) or any(find(e) == rf for e in failed):
                continue
            self.solver.stats["luks_aut_tests"] += 1
            Z = self.rooted(f)
            s = ch.run(Z)
            if s is None:
                failed.append(f)
                continue
            g = self.vertex_map(X, Z, s)
            gens.append(g)
            absorb(g)
        self.gens = gens
        self.find = find

    def iso(self, other):
        """A vertex map self -> other (connected, same color names), or None."""
        if self.g.n != other.g.n or len(self.edges) != len(other.edges):
            return None
        if Counter(self.invs) != Counter(other.invs):
            return None
        inv0 = self.invs[self.f0]
        e1 = next(i for i, v in enumerate(other.invs) if v == inv0)
        Z = other.rooted(e1)
        reps, seen = [self.f0], {self.find(self.f0)}
        for f in range(len(self.edges)):
            if self.invs[f] == inv0 and self.find(f) not in seen:
                seen.add(self.find(f))
                reps.append(f)
        for f in reps:
            self.solver.stats["luks_iso_tests"] += 1
            ch = self.chain(f)
            s = ch.run(Z)
            if s is not None:
                return self.vertex_map(ch.X, Z, s)
        return None


def _invert(p):
    r = [0] * len(p)
    for i, j in enumerate(p):
        r[j] = i
    return r


def bounded_iso(X, Y, solver=None, vcolors_x=None, vcolors_y=None, refine=True):
    """X, Y: adjacency matrices of undirected loopless graphs (any degree; the
    groups have composition factors in Sym(d - 1) for maximum degree d).
    Returns None if not isomorphic, else (sigma, aut_gens): sigma[i] is the
    image of vertex i (an isomorphism X -> Y) and aut_gens generate Aut(X)
    (vertex colors respected). solver: a Solver (default
    Solver(cameron_no_enum=True)); its stats count the reduction's work
    (luks_*)."""
    n = len(X)
    if len(Y) != n:
        return None
    if n == 0:
        return (), []
    solver = solver or Solver(cameron_no_enum=True)
    nx, ny = _neighbours(X), _neighbours(Y)
    cx, cy = _joint_names(vcolors_x or [0] * n, vcolors_y or [0] * n)
    if refine:
        r = refine_1wl(nx, ny, cx, cy)
        if r is None:
            solver.stats["luks_refine_reject"] += 1
            return None
        cx, cy = r
    elif Counter(cx) != Counter(cy):
        return None
    if sorted(map(len, nx)) != sorted(map(len, ny)):
        return None
    gx, gy = _Graph(nx, cx), _Graph(ny, cy)
    px, py = _components(nx), _components(ny)
    if len(px) != len(py):
        return None

    def key(g, part):
        return (len(part), sum(len(g.nbr[v]) for v in part), tuple(sorted(g.col[v] for v in part)))

    # isomorphism classes of X's components: [rep, [(part, iso rep -> part)], key]
    classes = []
    for part in px:
        k = key(gx, part)
        sub = _induced(gx, part)
        for C in classes:
            if C[2] == k:
                t = _component_iso(C[0], sub, solver)
                if t is not None:
                    C[1].append((part, t))
                    break
        else:
            rep = _Connected(sub, solver) if len(part) > 1 else _Single(sub)
            classes.append([rep, [(part, tuple(range(len(part))))], k])
    matches = [[] for _ in classes]
    for part in py:
        k = key(gy, part)
        sub = _induced(gy, part)
        for ci, C in enumerate(classes):
            if C[2] == k and len(matches[ci]) < len(C[1]):
                t = _component_iso(C[0], sub, solver)
                if t is not None:
                    matches[ci].append((part, t))
                    break
        else:
            return None
    sigma = [0] * n
    gens = []
    for C, M in zip(classes, matches):
        if len(M) != len(C[1]):
            return None
        rep, members = C[0], C[1]
        p1 = members[0][0]
        for g in rep.gens:              # Aut of the representative component
            h = list(range(n))
            for i, v in enumerate(p1):
                h[v] = p1[g[i]]
            gens.append(tuple(h))
        for (part, t), (ypart, s) in zip(members, M):
            ti = _invert(t)
            for i, v in enumerate(part):        # part -> rep -> ypart
                sigma[v] = ypart[s[ti[i]]]
        for part, t in members[1:]:     # swaps of the representative with each copy
            h = list(range(n))
            for i, v in enumerate(p1):
                h[v] = part[t[i]]
                h[part[t[i]]] = v
            gens.append(tuple(h))
    idn = identity(n)
    return tuple(sigma), [g for g in dict.fromkeys(gens) if g != idn]


class _Single:
    """A one-vertex component."""
    gens = ()

    def __init__(self, g):
        self.g = g


def _component_iso(rep, sub, solver):
    """A vertex map rep -> sub (connected graphs of equal size, edge count and
    color multiset), or None."""
    if isinstance(rep, _Single):
        return (0,) if rep.g.col == sub.col else None
    return rep.iso(_Connected(sub, solver, aut=False))
