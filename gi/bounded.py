"""Graph isomorphism for graphs of bounded degree by Luks's reduction
(E. M. Luks, Isomorphism of graphs of bounded valence can be tested in
polynomial time, JCSS 25 (1982); see also Helfgott's Bourbaki exposition,
arXiv:1710.04574, Exercise B.3) to string isomorphism under groups whose
composition factors embed in Sym(d - 1). Each layer's string isomorphism
problem is handed to Solver.solve.

    from gi.bounded import bounded_iso
    res = bounded_iso(X, Y)          # X, Y: adjacency matrices of simple graphs
    if res is not None:
        sigma, aut_gens = res        # isomorphism X -> Y and generators of Aut(X)

The reduction (connected X, Y; an oriented edge f = (u0, u1) of X and
f' = (u0', u1') of Y). Layer L_r is the set of vertices at distance r from
{u0, u1}, X_r the induced subgraph on L_0 + ... + L_r (with vertex colors).
Distances to {u0, u1} are the same in X_r as in X, so every automorphism of
X_{r+1} fixing u0 and u1 preserves the layers and restricts to one of X_r.
We keep

    G_r = Aut_f(X_r)  (u0, u1 fixed),    Iso_{f -> f'}(X_r, Y_r) = G_r sigma_r,

starting from the trivial group on L_0 = (u0, u1) (colors of u0, u1 must
match). One step r -> r + 1:

 (a) Down-degrees. delta(v) = |N(v) & L_{r+1}| for v in L_r. Every
     isomorphism of X_{r+1} preserves it, so G_r and sigma_r are replaced by
     the solution of the string problem "delta under G_r" (positions L_r).
     Call the result G' sigma'. Note delta(v) <= d - 1: v has a neighbour in
     L_{r-1} (or, for r = 0, the other end of f).
 (b) Down-edges. E = {(v, k) : v in L_r, k < delta(v)}, where (v, k) stands
     for the edge from v to its k-th neighbour in L_{r+1} in X, and for the
     edge from sigma'(v) to its k-th neighbour in L_{r+1}(Y) on the Y side.
     The group

         H = tau(G') x| prod_v Sym({v} x [delta(v)])      (acting on E)

     (tau = restriction of G' to the vertices with delta > 0; the first factor
     acts by (v, k) -> (v^g, k)) has composition factors among those of G'
     and of Sym(delta(v)), delta(v) <= d - 1. The string on singletons and
     unordered pairs of E: a singleton gets the color of the upper end of its
     edge, a pair {a, b} gets 1 if a and b have the same upper end, 2 if the
     upper ends are adjacent, 0 otherwise. The pair positions are the
     H-orbits of the pairs that are nonzero for X (a pair that is nonzero for
     Y but lies outside them refutes the step: H cannot map x's zeros onto
     it). Then Solver.solve gives Iso_H(x, y) = Aut_H(x) h0.

 Lifting. h in Aut_H(x) induces p = the map of lower ends on the vertices with
 delta > 0, which lies in tau(G'); let g = tau.lift(p). Define g+ = g on
 X_r, and w_a -> w_(h(a)) on L_{r+1} (w_a = upper end of a). It is well
 defined (x marks equal upper ends), maps L_r-L_{r+1} edges onto edges
 (h(v, k) = (g(v), k')), edges inside L_{r+1} onto edges and colors onto
 colors (x), so g+ is in G_{r+1}. Conversely every element of G_{r+1}
 restricts to G' and acts on the down-edges as an element of Aut_H(x); the
 kernel of that action is ker(tau) (fixed on L_{r+1}). Hence
     G_{r+1} = < g+ (h in gens of Aut_H(x)), ker(tau) >,
 so G_{r+1} lies in the class of groups with composition factors in
 Sym(d - 1) by induction. sigma_{r+1} = (g0 then sigma') on X_r and
 w_a -> (upper end of h0(a) in Y) on L_{r+1}, with g0 = tau.lift(p(h0)).

After the last layer G_R = Aut_f(X) and sigma_R: X -> Y maps f to f'.

Whole graphs. Oriented-edge invariants (colors of the ends and the multiset
of (dist to u0, dist to u1, color)) are compared first. Aut(X) is generated
by Aut_f0(X) and one isomorphism (X, f0) -> (X, f) for each f reached:
the oriented edges are tested in the invariant class of f0, skipping those in
the orbit of f0 under the automorphisms found so far and those in the orbit
of an edge that failed (a failure for f is a failure for every image of f
under Aut(X)). An isomorphism X -> Y exists iff (X, f) ~ (Y, f'0) for some f,
for one fixed f'0 of Y, and f can be taken up to Aut(X): one test per
Aut(X)-orbit in the matching invariant class. Tests against the same root
f0 reuse its groups G_r, so the solver's memo answers them in one-mode.
Disconnected graphs: components are grouped into isomorphism classes; Aut is
generated by the components' groups and the swaps of isomorphic components.

Vertex colors (vcolors_x, vcolors_y) are supported; refine=True first refines
them jointly by 1-WL (canonical names), which is exact and keeps the groups
in the class above. Graphs must be undirected and loopless.
"""
