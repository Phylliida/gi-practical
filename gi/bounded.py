# -- graphs -------------------------------------------------------------------
class _Graph:
    """A vertex-colored simple graph: nbr[v] sorted neighbour lists."""
    __slots__ = ("n", "nbr", "col")

    def __init__(self, nbr, col):
        self.n, self.nbr, self.col = len(nbr), nbr, col


def _neighbours(A):
    n = len(A)
    nbr = []
    for i in range(n):
        if A[i][i]:
            raise NotSimple("loops are not supported")
        row = []
        for j in range(n):
            if A[i][j]:
                if not A[j][i]:
                    raise NotSimple("directed graphs are not supported")
                row.append(j)
        nbr.append(row)
    return nbr


def _joint_names(cx, cy):
    vals = set(cx) | set(cy)
    try:
        srt = sorted(vals)
    except TypeError:
        srt = sorted(vals, key=repr)
    rank = {v: i for i, v in enumerate(srt)}
    return [rank[c] for c in cx], [rank[c] for c in cy]


def refine_1wl(nx, ny, cx, cy):
    """Joint 1-WL of two graphs (neighbour lists nx, ny, int colors cx, cy)
    by gi.wl.refine on the disjoint union, so a color name means the same in
    both: every isomorphism X -> Y (extended by its inverse) is an
    automorphism of the union, hence maps the refined x-colors onto the
    refined y-colors. None if the color histograms differ."""
    n = len(nx)
    if Counter(cx) != Counter(cy):
        return None
    union = nx + [[v + n for v in r] for r in ny]
    c = wl_refine(union, list(cx) + list(cy))
    cx2, cy2 = c[:n], c[n:]
    return (cx2, cy2) if Counter(cx2) == Counter(cy2) else None


def _components(nbr):
    n = len(nbr)
    comp = [-1] * n
    out = []
    for s in range(n):
        if comp[s] >= 0:
            continue
        comp[s] = len(out)
        part = [s]
        for v in part:
            for w in nbr[v]:
                if comp[w] < 0:
                    comp[w] = comp[s]
                    part.append(w)
        out.append(sorted(part))
    return out


def _induced(g, part):
    loc = {v: i for i, v in enumerate(part)}
    return _Graph([[loc[w] for w in g.nbr[v]] for v in part], [g.col[v] for v in part])


# -- the layered structure from an oriented edge ---------------------------------
def rooted_colors(g, u0, u1, stable=False):
    """1-WL colors of g with u0 and u1 individualized (gi.wl.refine): the
    color names are a function of the rooted isomorphism type, so every
    isomorphism (X, (u0, u1)) -> (Z, (u0', u1')) maps the colors of X onto
    those of Z, and they can be added to the rooted graphs without changing
    their rooted isomorphisms. They are in general finer than distances from
    the root (1-WL computes those). stable: g.col is equitable."""
    return wl_refine(g.nbr, g.col, (u0, u1), stable)


class _Seed:
    """A rooted graph before layering: g, the root edge (u0, u1) and the
    vertex colors used (rooted 1-WL colors or g's own); layered versions
    are cached per layer plan."""
    __slots__ = ("g", "u0", "u1", "col", "layered")

    def __init__(self, g, u0, u1, col):
        self.g, self.u0, self.u1, self.col = g, u0, u1, col
        self.layered = {}


def class_plan(g, col, u0, u1):
    """A layer plan: a list of layers after L_0 = (u0, u1), each a list of
    color names whose classes form the layer. It depends only on the colored
    graph and the root (all ties are broken by color names), so any rooted
    isomorphism respecting the colors maps the layers of one graph onto the
    same-named layers of the other.

    Greedy: with P the vertices placed so far, a pending class is
    "determined" if its vertices have pairwise distinct up-sets N(v) & P;
    all determined classes form the next layer (they add no symmetry: a
    vertex is fixed by its up-set). Otherwise the next layer is the single
    class minimizing (a twin block of >= 3 vertices?, a twin block of 2
    with a nonempty up-set?, number of twin pairs, - placed vertices at
    distance 2, color): twin pairs with an empty up-set add a direct Z_2
    factor, which keeps G_r elementary abelian (see _Chain.layer2_ea).

    Returns None (use BFS layers) as soon as the next layer would hold a
    twin block of >= 3 vertices: then the colors are too coarse for this
    order to help (e.g. hypercubes, where class layers make big symmetric
    groups that BFS layers avoid). This also depends only on X."""
    nbr = g.nbr
    n = g.n
    members = {}
    for v in range(n):
        members.setdefault(col[v], []).append(v)
    done = [False] * n
    near = {}                           # c -> number of paths (x in c) - w - z with z placed
    pending = set(members) - {col[u0], col[u1]}
    struct, det = {}, set()             # c -> (big >= 3, risk, pairs) for undetermined c
    dirty = set()

    def placed(v):                      # v was placed (done[v] is already set)
        for w in nbr[v]:
            dirty.add(col[w])
            for x in nbr[w]:
                c = col[x]
                near[c] = near.get(c, 0) + 1

    done[u0] = done[u1] = True
    for u in (u0, u1):
        placed(u)
    dirty |= pending
    plan = []
    while pending:
        for c in dirty:
            if c not in pending:
                continue
            ms = members[c]
            if len(ms) == 1:
                big = 1
            else:
                ups = Counter(frozenset([w for w in nbr[v] if done[w]]) for v in ms)
                big = max(ups.values())
            if big == 1:
                det.add(c)
                struct.pop(c, None)
            else:
                risk = any(k >= 2 and S for S, k in ups.items())
                pairs = sum(k for k in ups.values() if k >= 2)
                struct[c] = (big >= 3, risk, pairs)
                det.discard(c)
        dirty = set()
        if det:
            layer = sorted(det)
            det = set()
        else:
            c = min(pending, key=lambda c: (struct[c], -near.get(c, 0), c))
            if struct[c][0]:            # a twin block of >= 3: BFS layers instead
                return None
            layer = [c]
        plan.append(layer)
        for c in layer:
            pending.discard(c)
            struct.pop(c, None)
            for v in members[c]:
                done[v] = True
        if pending:
            for c in layer:
                for v in members[c]:
                    placed(v)
    return plan


class _Rooted:
    """The layers of a connected graph from the oriented edge (u0, u1):
    L_0 = (u0, u1), then either the BFS layers (plan None) or the color
    classes of a class_plan. Vertices are renumbered by layers: order[i] is
    the vertex of index i, start[r] the first index of layer r (start[-1] =
    n). up[i] is the set of indices of the neighbours of index i in earlier
    layers (for BFS layers: the previous one), adj[i] the set of all
    neighbour indices, col[i] the color. The attachment classes of layer
    r + 1 (index sets up[t] -> sorted members) are cached per r. ok is False
    if the graph does not fit the plan (then it is not isomorphic to the
    graph the plan was made for)."""
    __slots__ = ("order", "start", "up", "adj", "col", "ok", "_att", "_inner")

    def __init__(self, g, u0, u1, col=None, plan=None):
        n = g.n
        if col is None:
            col = g.col
        self.ok = True
        lay = [-1] * n
        lay[u0] = lay[u1] = 0
        order = [u0, u1]
        start = [0, 2]
        if plan is None:
            cur = order[:]
            while True:
                nxt = []
                for v in cur:
                    for w in g.nbr[v]:
                        if lay[w] < 0:
                            lay[w] = lay[v] + 1
                            nxt.append(w)
                if not nxt:
                    break
                order.extend(nxt)
                start.append(len(order))
                cur = nxt
            if len(order) != n:
                raise ValueError("graph is not connected")
        else:
            where = {}
            for r, cs in enumerate(plan):
                for c in cs:
                    where[c] = r
            byr = [[] for _ in plan]
            for v in range(n):
                if v == u0 or v == u1:
                    continue
                r = where.get(col[v])
                if r is None:
                    self.ok = False
                    return
                byr[r].append(v)
            for r, vs in enumerate(byr):
                vs.sort(key=lambda v: (col[v], v))
                for v in vs:
                    lay[v] = r + 1
                order.extend(vs)
                start.append(len(order))
        pos = [0] * n
        for i, v in enumerate(order):
            pos[v] = i
        self.order, self.start = order, start
        self.adj = [frozenset(pos[w] for w in g.nbr[v]) for v in order]
        self.col = [col[v] for v in order]
        self.up = [frozenset(pos[w] for w in g.nbr[v] if lay[w] < lay[v]) for v in order]
        self._att = {}
        self._inner = {}

    def attachments(self, r):
        """{up-set: members of layer r + 1 with that up-set, sorted by (color,
        index)} (the twin classes over layer r)."""
        a = self._att.get(r)
        if a is None:
            a = {}
            for t in range(self.start[r + 1], self.start[r + 2]):
                a.setdefault(self.up[t], []).append(t)
            col = self.col
            for ts in a.values():
                ts.sort(key=lambda t: (col[t], t))
            self._att[r] = a
        return a

    def inner_edges(self, r):
        """The number of edges inside layer r + 1."""
        e = self._inner.get(r)
        if e is None:
            b, c = self.start[r + 1], self.start[r + 2]
            e = self._inner[r] = sum(1 for t in range(b, c) for u in self.adj[t] if t < u < c)
        return e


